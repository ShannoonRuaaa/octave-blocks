function state = ob_conditional_state (model, start_time, options = [])
  if (isempty(options)), options = ob_execution_options (model); endif
  state = struct ('initialized', false, 'child', [], 'outputs', {options.initial_outputs}, ...
                  'was_enabled', false, 'previous_sign', sign(options.initial_control), ...
                  'last_rising', false, 'last_falling', false, 'last_executed', false, ...
                  'last_sample', start_time, 'advance_interval', 0, 'executions', [], ...
                  'control_sign', sign(options.initial_control), ...
                  'continuous_elapsed', 0, 'continuous_active_since', []);
endfunction
