function lines = ob_emit_c_event_math (root)
  % Model-independent guard metadata and frozen-regime operations for C export.
  guards = root.event_inventory;
  count = numel (guards); storage = max (1,count);
  kinds = zeros (1,storage); modes = zeros (1,storage);
  boundaries = zeros (1,storage); channels = zeros (1,storage);
  paths = repmat ({'""'},1,storage);
  for index = 1:count
    guard = guards(index);
    switch (guard.side)
      case 'threshold', kinds(index) = 0;
      case 'lower', kinds(index) = 1;
      case 'upper', kinds(index) = 2;
      case 'control', kinds(index) = 3;
      otherwise, error ('ob_emit_c_event_math: unsupported guard side');
    endswitch
    modes(index) = guard.mode_id-1;
    boundaries(index) = guard.boundary;
    channels(index) = guard.channel;
    paths{index} = ['"' strrep(strtrim(sprintf('%d ',guard.path)),' ','/') '"'];
  endfor
  lines = {sprintf('enum { OB_EVENT_COUNT=%d, OB_EVENT_STORAGE=%d };',count,storage), ...
      'enum { OB_EVENT_THRESHOLD=0, OB_EVENT_LOWER=1, OB_EVENT_UPPER=2, OB_EVENT_CONTROL=3 };', ...
      'typedef struct {double value[OB_EVENT_STORAGE];unsigned char active[OB_EVENT_STORAGE];int mode[OB_EVENT_STORAGE];} ob_event_snapshot;', ...
      ['const int ob_event_kind[OB_EVENT_STORAGE]={' integers(kinds) '};'], ...
      ['const size_t ob_event_mode[OB_EVENT_STORAGE]={' integers(modes) '};'], ...
      ['const double ob_event_boundary[OB_EVENT_STORAGE]={' numbers(boundaries) '};'], ...
      ['const size_t ob_event_channel[OB_EVENT_STORAGE]={' integers(channels) '};'], ...
      ['const char *const ob_event_path[OB_EVENT_STORAGE]={' strjoin(paths,',') '};'], ...
      'static int ob_event_sign(double value){return (value>0.0)-(value<0.0);}', ...
      'static int ob_event_side(size_t index,const int *mode){', ...
      '  const int regime=mode[ob_event_mode[index]];', ...
      '  switch(ob_event_kind[index]){', ...
      '    case OB_EVENT_THRESHOLD:return 2*(regime!=0)-1;', ...
      '    case OB_EVENT_LOWER:return 1-2*(regime==-1);', ...
      '    case OB_EVENT_UPPER:return 2*(regime==1)-1;', ...
      '    default:return ob_event_sign((double)regime);', ...
      '  }', ...
      '}', ...
      'static int ob_event_crossed(const ob_event_snapshot *before,const ob_event_snapshot *after,const int *mode){'};
  if (count > 0)
    lines = [lines { ...
      '  for(size_t i=0;i<OB_EVENT_COUNT;++i){', ...
      '    if(!before->active[i]||!after->active[i])continue;', ...
      '    const double a=before->value[i],b=after->value[i];', ...
      '    if((a<0.0&&b>=0.0)||(a>0.0&&b<=0.0))return 1;', ...
      '    if(a==0.0&&b!=0.0){', ...
      '      if((ob_event_kind[i]==OB_EVENT_CONTROL&&mode[ob_event_mode[i]]==0)||ob_event_sign(b)!=ob_event_side(i,mode))return 1;', ...
      '    }', ...
      '  }'}];
  else
    lines = [lines {'  (void)before;(void)after;(void)mode;(void)ob_event_side;'}];
  endif
  lines = [lines {'  return 0;', '}', ...
      'static void ob_event_propose(const ob_event_snapshot *at,const ob_event_snapshot *probe,const int *mode,int *next){', ...
      '  memcpy(next,at->mode,OB_EVENT_STORAGE*sizeof(int));'}];
  if (count > 0)
    lines = [lines { ...
      '  for(size_t i=0;i<OB_EVENT_COUNT;++i){', ...
      '    if(at->active[i]&&at->value[i]==0.0&&ob_event_kind[i]!=OB_EVENT_CONTROL)', ...
      '      next[ob_event_mode[i]]=mode[ob_event_mode[i]];', ...
      '  }', ...
      '  for(size_t i=0;i<OB_EVENT_COUNT;++i){', ...
      '    if(!at->active[i]||!probe->active[i]||at->value[i]!=0.0||ob_event_kind[i]==OB_EVENT_CONTROL)continue;', ...
      '    const int direction=ob_event_sign(probe->value[i]);', ...
      '    if(direction==0)continue;', ...
      '    const size_t slot=ob_event_mode[i];', ...
      '    switch(ob_event_kind[i]){', ...
      '      case OB_EVENT_THRESHOLD:next[slot]=direction>0;break;', ...
      '      case OB_EVENT_LOWER:if(direction<0)next[slot]=-1;else if(next[slot]==-1)next[slot]=0;break;', ...
      '      case OB_EVENT_UPPER:if(direction>0)next[slot]=1;else if(next[slot]==1)next[slot]=0;break;', ...
      '      default:break;', ...
      '    }', ...
      '  }'}];
  else
    lines = [lines {'  (void)probe;(void)mode;'}];
  endif
  lines = [lines {'}'}];
endfunction

function text = integers (values)
  text = strjoin (arrayfun(@(value)sprintf('%d',value),values,'uniformoutput',false),',');
endfunction

function text = numbers (values)
  tokens = arrayfun (@(value)sprintf('%.17g',value),values,'uniformoutput',false);
  for index = 1:numel(tokens)
    if (isempty(strfind(tokens{index},'.')) && isempty(strfind(lower(tokens{index}),'e')))
      tokens{index} = [tokens{index} '.0'];
    endif
  endfor
  text = strjoin (tokens,',');
endfunction
