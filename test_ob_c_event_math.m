function sources = test_ob_c_event_math (directory)
  % Generate isolated C helper checks; this does not enable event C export.
  if (! ischar(directory) || rows(directory)!=1 || isempty(directory))
    error ('test_ob_c_event_math: supply an artifact directory');
  endif
  if (! exist(directory,'dir')), mkdir(directory); endif
  [unit, guards] = ob_c_event_inventory (ob_c_conditional_unit(ob_control_example()));
  control = guards(1); control.type='Conditional Subsystem'; control.side='control';
  control.path=99; control.mode_id=6; control.channel=1; control.boundary=0;
  guards(end+1)=control; unit.event_inventory=guards;
  populated = {'#include <assert.h>', ...
    'int main(void){', ...
    '  ob_event_snapshot a={0},b={0};int mode[OB_EVENT_STORAGE]={0},next[OB_EVENT_STORAGE];', ...
    '  assert(OB_EVENT_COUNT==6&&ob_event_mode[1]==0&&ob_event_kind[5]==OB_EVENT_CONTROL);', ...
    '  assert(ob_event_boundary[0]==0.0&&ob_event_boundary[1]==3.0);', ...
    '  assert(strcmp(ob_event_path[5],"99")==0&&ob_event_channel[5]==1);', ...
    '  a.active[0]=b.active[0]=1;a.value[0]=-1.0;b.value[0]=0.0;mode[0]=-1;', ...
    '  assert(ob_event_crossed(&a,&b,mode));b.active[0]=0;assert(!ob_event_crossed(&a,&b,mode));', ...
    '  a=(ob_event_snapshot){0};b=(ob_event_snapshot){0};', ...
    '  a.active[4]=b.active[4]=1;b.value[4]=-1.0;mode[4]=1;', ...
    '  assert(ob_event_crossed(&a,&b,mode));mode[4]=0;assert(!ob_event_crossed(&a,&b,mode));', ...
    '  a=(ob_event_snapshot){0};b=(ob_event_snapshot){0};', ...
    '  a.active[5]=b.active[5]=1;b.value[5]=1.0;mode[5]=0;', ...
    '  assert(ob_event_crossed(&a,&b,mode));mode[5]=1;assert(!ob_event_crossed(&a,&b,mode));', ...
    '  a=(ob_event_snapshot){0};b=(ob_event_snapshot){0};', ...
    '  a.active[0]=b.active[0]=1;b.value[0]=.5;mode[0]=-1;', ...
    '  ob_event_propose(&a,&b,mode,next);assert(next[0]==0);', ...
    '  a.active[0]=b.active[0]=0;a.active[1]=b.active[1]=1;b.value[1]=-.5;mode[0]=1;', ...
    '  ob_event_propose(&a,&b,mode,next);assert(next[0]==0);', ...
    '  a.active[0]=b.active[0]=1;b.value[0]=-.5;mode[0]=0;', ...
    '  ob_event_propose(&a,&b,mode,next);assert(next[0]==-1);', ...
    '  b.value[0]=b.value[1]=.5;ob_event_propose(&a,&b,mode,next);assert(next[0]==1);', ...
    '  a.active[5]=b.active[5]=1;a.mode[5]=-1;b.value[5]=1.0;', ...
    '  ob_event_propose(&a,&b,mode,next);assert(next[5]==-1);', ...
    '  assert(ob_event_sign(-0.0)==0&&ob_event_sign(-1.0)==-1);return 0;', ...
    '}'};
  sources = {fullfile(directory,'event_math.c'),fullfile(directory,'event_math_empty.c')};
  write_case (sources{1}, ob_emit_c_event_math(unit), populated);
  unit.event_inventory=guards([]);
  empty = {'#include <assert.h>', ...
    'int main(void){', ...
    '  ob_event_snapshot a={0},b={0};int mode[OB_EVENT_STORAGE]={0},next[OB_EVENT_STORAGE];', ...
    '  assert(OB_EVENT_COUNT==0);assert(!ob_event_crossed(&a,&b,mode));', ...
    '  ob_event_propose(&a,&b,mode,next);assert(next[0]==0);return 0;', ...
    '}'};
  write_case (sources{2}, ob_emit_c_event_math(unit), empty);
  disp ('Prepared populated and empty C event-math helper tests');
endfunction

function write_case (file, lines, checks)
  text = [strjoin([{'#include <stddef.h>','#include <string.h>'} lines checks],char(10)) char(10)];
  fid=fopen(file,'wb');
  if (fid<0), error('test_ob_c_event_math: cannot write %s',file); endif
  unwind_protect
    assert(fwrite(fid,text,'char')==numel(text));
  unwind_protect_cleanup
    fclose(fid);
  end_unwind_protect
endfunction
