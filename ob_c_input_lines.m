function lines = ob_c_input_lines (inputs, continuous)
  % C support code for normalized sampled root inputs and host callbacks.
  lines = {};
  if (isempty (inputs)), return; endif
  counts = cellfun (@(s) prod(s.shape), inputs);
  offsets = cumsum ([0 counts(1:end-1)]);
  for port = 1:numel (inputs)
    signal = inputs{port};
    add (sprintf ('static const double ob_input_t%d[%d] = {%s};', port, numel(signal.t), numbers(signal.t(:)')));
    add (sprintf ('static const double ob_input_v%d[%d] = {%s};', port, numel(signal.values), numbers(reshape(signal.values', 1, []))));
  endfor
  add ('static void ob_sample_input(const double *times, const double *samples, size_t rows,', ...
       '                            size_t components, int linear, double time, int left, double *out) {', ...
       '  size_t row = 0;',
       '  while (row + 1 < rows && time >= times[row + 1]) ++row;', ...
       '  if (!linear) {', ...
       '    if (left && row > 0 && time == times[row]) --row;', ...
       '    memcpy(out, samples + row*components, components*sizeof(double));', ...
       '  } else if (time <= times[0] || row + 1 == rows) {', ...
       '    memcpy(out, samples + row*components, components*sizeof(double));', ...
       '  } else {', ...
       '    const double weight = (time - times[row])/(times[row + 1] - times[row]);', ...
       '    for (size_t i = 0; i < components; ++i)', ...
       '      out[i] = (1.0-weight)*samples[row*components + i] + weight*samples[(row+1)*components + i];', ...
       '  }', '}', ...
       'static int ob_read_inputs(const ob_model *model, double time, int left, double *values) {', ...
       '  if (model->input_provider) {', ...
       '    for (size_t i = 0; i < OB_INPUT_VALUE_COUNT; ++i) values[i] = NAN;', ...
       '    if (model->input_provider(time, left, values, OB_INPUT_VALUE_COUNT, model->input_user) != OB_OK)', ...
       '      return OB_INPUT_ERROR;', ...
       '  } else {');
  for port = 1:numel (inputs)
    add (sprintf ('    ob_sample_input(ob_input_t%d, ob_input_v%d, %d, %d, %d, time, left, values + %d);', ...
                  port, port, numel(inputs{port}.t), counts(port), strcmp(inputs{port}.method, 'linear'), offsets(port)));
  endfor
  add ('  }', ...
       '  for (size_t i = 0; i < OB_INPUT_VALUE_COUNT; ++i) if (!isfinite(values[i])) return OB_NONFINITE;', ...
       '  return OB_OK;', '}');
  if (continuous)
    add ('static int ob_next_input_boundary(const ob_model *model, double after, double *before) {', ...
         '  double event = *before;', ...
         '  if (model->input_provider) {', ...
         '    if (model->input_event) {', ...
         '      event = model->input_event(after, *before, model->input_user);', ...
         '      if (!isfinite(event) || event <= after || event > *before) return OB_INPUT_ERROR;', ...
         '    }', '  } else {');
    for port = 1:numel (inputs)
      add (sprintf ('    for (size_t i = 0; i < %d; ++i)', numel(inputs{port}.t)), ...
           sprintf ('      if (ob_input_t%d[i] > after && ob_input_t%d[i] < event) event = ob_input_t%d[i];', port, port, port));
    endfor
    add ('  }', '  *before = event;', '  return OB_OK;', '}');
  endif

  function add (varargin)
    lines = [lines varargin];
  endfunction
endfunction

function text = numbers (values)
  items = arrayfun (@number, values, 'uniformoutput', false);
  text = strjoin (items, ',');
endfunction

function text = number (value)
  text = sprintf ('%.17g', value);
  if (isempty (strfind(text, '.')) && isempty (strfind(lower(text), 'e')))
    text = [text '.0'];
  endif
endfunction
