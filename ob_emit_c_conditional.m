function lines = ob_emit_c_conditional (root, times)
  % One C translation unit; child symbols are explicit path-derived namespaces.
  lines = {'/* Generated by Octave Blocks: typed execution units and numeric output proxies. */', ...
    '#include <math.h>','#include <float.h>','#include <stddef.h>','#include <string.h>', ...
    '#ifdef OB_STANDALONE','#include <stdio.h>','#endif', ...
    'enum { OB_OK=0, OB_BAD_ARGUMENT=1, OB_NONFINITE=2, OB_INPUT_ERROR=3 };', ...
    'typedef enum { OB_INTERVAL_ELAPSED=0, OB_INTERVAL_INHERITED=1, OB_INTERVAL_PERIOD=2 } ob_interval_kind;', ...
    'typedef int (*ob_input_provider)(double,int,double*,size_t,void*);', ...
    'typedef double (*ob_input_event)(double,double,void*);', ...
    'typedef struct {double origin;const unsigned char *due;const double *tick;} ob_clock_frame;'};
  clock_mode = !isempty(root.descendant_clocks);
  if(clock_mode)
    add(sprintf('enum { OB_CLOCK_COUNT=%d };',numel(root.clock_inventory)), ...
      ['const double ob_clock_period[OB_CLOCK_COUNT]={' nums(arrayfun(@(c)c.rate(1),root.clock_inventory)) '};'], ...
      ['const double ob_clock_offset[OB_CLOCK_COUNT]={' nums(arrayfun(@(c)c.rate(2),root.clock_inventory)) '};']);
    labels=cellfun(@(p)['"' strrep(strtrim(sprintf('%d ',p)),' ','/') '"'],{root.clock_inventory.path},'uniformoutput',false);
    add(['const char *const ob_clock_path[OB_CLOCK_COUNT]={' strjoin(labels,',') '};']);
  endif
  if (has_multiply(root))
    add('static void ob_cc_mul(double *o,const double *a,size_t ar,size_t ac,const double *b,size_t br,size_t bc) {', ...
      '  if(ar*ac==1) { for(size_t i=0;i<br*bc;++i)o[i]=a[0]*b[i]; }', ...
      '  else if(br*bc==1) { for(size_t i=0;i<ar*ac;++i)o[i]=a[i]*b[0]; }', ...
      '  else for(size_t c=0;c<bc;++c)for(size_t r=0;r<ar;++r){double x=0.0;', ...
      '    for(size_t k=0;k<ac;++k){x+=a[r+k*ar]*b[k+c*br];} o[r+c*ar]=x;}', '}');
  endif
  emit_unit(root);
  add('#ifdef OB_STANDALONE',['static const double ob_times[]={' nums(times) '};'], ...
    'int main(void){ ob_model model; if(ob_model_init(&model,ob_times[0])!=OB_OK)return 1;', ...
    '  printf("time"); for(size_t b=0;b<OB_BLOCK_COUNT;++b)', ...
    '    for(size_t e=0;e<ob_block_rows[b]*ob_block_cols[b];++e)printf(",b%s_e%zu",ob_block_path[b],e+1);', ...
    '  printf("\n");', ...
    '  for(size_t s=0;s<sizeof(ob_times)/sizeof(ob_times[0]);++s){', ...
    '    if(s&&ob_model_step(&model,ob_times[s])!=OB_OK){fprintf(stderr,"Simulation failed at sample %zu\n",s);return 2;}', ...
    '    printf("%.17g",model.time);');
  if (root.value_count > 0), add('    for(size_t i=0;i<OB_VALUE_COUNT;++i)printf(",%.17g",model.value[i]);'); endif
  add('    printf("\n"); } return 0; }','#endif');

  function add(varargin), lines=[lines varargin]; endfunction

  function emit_unit(u)
    for child = u.children
      if (! isempty(child{1})), emit_unit(child{1}); endif
    endfor
    p=u.prefix; t=[p 'model']; count=max(1,u.n);
    add(sprintf('enum { %s=%d,%s=%d,%s=%d,%s=%d,%s=%d,%s=%d };', ...
      cn(u,'BLOCK_COUNT'),u.n,cn(u,'VALUE_COUNT'),u.value_count,cn(u,'STATE_COUNT'),u.state_count, ...
      cn(u,'VALUE_STORAGE'),max(1,u.value_count),cn(u,'STATE_STORAGE'),max(1,u.state_count), ...
      cn(u,'INPUT_VALUE_COUNT'),u.input_count));
    if (u.root)
      add(sprintf('enum { OB_INPUT_PORT_COUNT=%d, OB_INPUT_STORAGE=%d, OB_INPUT_PORT_STORAGE=%d };', ...
        numel(u.flat.inputs),max(1,u.input_count),max(1,numel(u.flat.inputs))));
    endif
    add('typedef struct {',sprintf('  double state[%s],pending[%s],value[%s];',cn(u,'STATE_STORAGE'),cn(u,'STATE_STORAGE'),cn(u,'VALUE_STORAGE')), ...
      sprintf('  unsigned char pending_valid[%d];',count), ...
      sprintf('  double tick[%d];',count), ...
      '  double time,start_time; int initialized;', ...
      sprintf('  double held[%d];',max(1,u.out_count)), ...
      '  double last_sample,advance_interval; int was_enabled,previous_sign,last_rising,last_falling,last_executed;');
    if (!u.root && (u.has_continuous || (clock_mode && u.clocked)))
      add(sprintf('  double major_value[%s];',cn(u,'VALUE_STORAGE')));
    endif
    if (u.root), add('  ob_input_provider input_provider; ob_input_event input_event; void *input_user;'); endif
    if(u.root&&clock_mode),add('  double clock_tick[OB_CLOCK_COUNT];');endif
    for id=1:u.n
      if (! isempty(u.children{id})), add(sprintf('  %smodel child_%d;',u.children{id}.prefix,id)); endif
    endfor
    add(['} ' t ';']);
    for id=1:u.n
      b=u.flat.blocks(id);
      if (u.numeric_state(id)||any(strcmp(b.type,{'Constant','Gain'})))
        add(sprintf('static const double %sp%d[%d]={%s};',p,id,numel(b.value),nums(b.value(:)')));
      endif
    endfor
    if (u.root)
      emit_metadata(u);
      lines=[lines ob_c_input_lines(u.flat.inputs,u.has_continuous)];
    else
      initial=[];
      for output=u.options.initial_outputs, initial=[initial output{1}(:)']; endfor
      if (isempty(initial)), initial=0; endif
      add(sprintf('static const double %sinitial[%d]={%s};',p,max(1,u.out_count),nums(initial)));
      add(sprintf('static void %sgate_reset(%s *m,double time){',p,t), ...
        '  memset(m,0,sizeof(*m));',sprintf('  m->last_sample=time; m->previous_sign=%d;',sign(u.options.initial_control)), ...
        sprintf('  memcpy(m->held,%sinitial,%d*sizeof(double));',p,u.out_count),'}');
    endif
    if(!u.root&&strcmp(u.options.mode,'enabled')),emit_suspend(u);endif
    emit_eval(u);
    if (u.root)
      if(clock_mode),emit_clocked_root(u);else emit_root(u);endif
    elseif(clock_mode&&u.clocked),emit_clocked_child(u);
    else emit_child(u);endif
  endfunction

  function emit_metadata(u)
    add(['const size_t ob_block_offset[OB_BLOCK_COUNT]={' ints(u.offsets) '};'], ...
      ['const size_t ob_block_rows[OB_BLOCK_COUNT]={' ints(cellfun(@(x)x(1),u.shapes)) '};'], ...
      ['const size_t ob_block_cols[OB_BLOCK_COUNT]={' ints(cellfun(@(x)x(2),u.shapes)) '};']);
    paths=cellfun(@(x)['"' strrep(strtrim(sprintf('%d ',x)),' ','/') '"'],u.paths,'uniformoutput',false);
    add(['const char *const ob_block_path[OB_BLOCK_COUNT]={' strjoin(paths,',') '};']);
    in_offsets=u.input_offsets; in_rows=cellfun(@(x)x.shape(1),u.flat.inputs); in_cols=cellfun(@(x)x.shape(2),u.flat.inputs);
    if(isempty(in_offsets)),in_offsets=in_rows=in_cols=0;endif
    add(['const size_t ob_input_offset[OB_INPUT_PORT_STORAGE]={' ints(in_offsets) '};'], ...
      ['const size_t ob_input_rows[OB_INPUT_PORT_STORAGE]={' ints(in_rows) '};'], ...
      ['const size_t ob_input_cols[OB_INPUT_PORT_STORAGE]={' ints(in_cols) '};'], ...
      ['const double ob_sample_period[OB_BLOCK_COUNT]={' nums(u.flat.sample_times(:,1)') '};'], ...
      ['const double ob_sample_offset[OB_BLOCK_COUNT]={' nums(u.flat.sample_times(:,2)') '};']);
  endfunction

  function emit_eval(u)
    p=u.prefix;t=[p 'model'];
    add(sprintf('static int %seval(const %s *m,double time,const double *state,double *v,int left,const double *external,const unsigned char *hit,%s *event_model,double inherited_interval,ob_interval_kind interval_kind,const ob_clock_frame *frame){',p,t,t), ...
      '  (void)m;(void)time;(void)state;(void)v;(void)left;(void)external;(void)hit;(void)event_model;(void)inherited_interval;(void)interval_kind;(void)frame;');
    if (u.root && u.input_count>0)
      add('  double root_input[OB_INPUT_STORAGE]; int input_status=ob_read_inputs(m,time,left,root_input);', ...
        '  if(input_status!=OB_OK){return input_status;} external=root_input;');
    endif
    for id=u.order
      block=u.flat.blocks(id); sources=u.edges(u.edges(:,2)==id,1); o=u.offsets(id); n=u.sizes(id);
      switch(block.type)
        case 'Multiple Function'
          emit_multiple_function(u,id,sources(1));
        case 'Function Output'
          % The core computes both proxy buffers together, before either is read.
        case 'Conditional Subsystem'
          child=u.children{id};
          gate_interval='inherited_interval';gate_kind='interval_kind';
          if(strcmp(child.options.mode,'enabled')&&u.flat.sample_times(id,1)>0)
            gate_interval=num(u.flat.sample_times(id,1));gate_kind='OB_INTERVAL_PERIOD';
          endif
          if(clock_mode&&child.clocked)
            add('  {',sprintf('    double child_input[%d];',max(1,child.input_count)), ...
                sprintf('    %smodel local=m->child_%d;',child.prefix,id), ...
                sprintf('    %smodel *context=event_model?&event_model->child_%d:&local;',child.prefix,id));
            if(child.input_count==0),add('    child_input[0]=0.0;');endif
            for port=1:numel(sources)-1
              add(sprintf('    memcpy(child_input+%d,v+%d,%d*sizeof(double));',child.input_offsets(port),u.offsets(sources(port)),child.input_sizes(port)));
            endfor
            add(sprintf('    const int major=hit&&hit[%d];',id-1), ...
                sprintf('    if(major||(%s)){int status=%sclock_event(context,time,child_input,v[%d],%s,%s,major,frame);',clock_test(child.all_clocks),child.prefix,u.offsets(sources(end)),gate_interval,gate_kind), ...
                '      if(status!=OB_OK)return status;}', ...
                sprintf('    int status=%sflow(context,time,child_input,left);if(status!=OB_OK)return status;',child.prefix));
            emit_proxy_copies(u,id,child,'context->held');
            add('  }');continue;
          endif
          if (child.has_continuous)
            add('  {',sprintf('    double child_input[%d];',max(1,child.input_count)), ...
                sprintf('    %smodel local=m->child_%d;',child.prefix,id), ...
                sprintf('    %smodel *context=event_model?&event_model->child_%d:&local;',child.prefix,id));
            if (child.input_count==0),add('    child_input[0]=0.0;');endif
            for port=1:numel(sources)-1
              add(sprintf('    memcpy(child_input+%d,v+%d,%d*sizeof(double));',child.input_offsets(port),u.offsets(sources(port)),child.input_sizes(port)));
            endfor
            add(sprintf('    if(hit&&hit[%d]){int status=%sgate_event(context,time,child_input,v[%d],%s,%s);',id-1,child.prefix,u.offsets(sources(end)),gate_interval,gate_kind), ...
                '      if(status!=OB_OK)return status;}', ...
                sprintf('    int status=%sflow(context,time,child_input,left);if(status!=OB_OK)return status;',child.prefix));
            proxies=u.edges(u.edges(:,1)==id,2);
            for proxy=reshape(proxies,1,[])
              port=u.flat.blocks(proxy).value;
              add(sprintf('    memcpy(v+%d,context->held+%d,%d*sizeof(double));',u.offsets(proxy),child.out_offsets(port),child.out_sizes(port)));
            endfor
            add('  }');
            continue;
          endif
          add(sprintf('  if(hit&&hit[%d]){',id-1),sprintf('    double child_input[%d];',max(1,child.input_count)));
          if (child.input_count==0),add('    child_input[0]=0.0;');endif
          for port=1:numel(sources)-1
            add(sprintf('    memcpy(child_input+%d,v+%d,%d*sizeof(double));',child.input_offsets(port),u.offsets(sources(port)),child.input_sizes(port)));
          endfor
          add(sprintf('    int status=%sgate_event(&event_model->child_%d,time,child_input,v[%d],%s,%s);',child.prefix,id,u.offsets(sources(end)),gate_interval,gate_kind), ...
            '    if(status!=OB_OK)return status;','  }');
        case 'Conditional Output'
          core=sources(1); child=u.children{core}; port=block.value;
          if (!child.has_continuous && !(clock_mode&&child.clocked))
            add(sprintf('  memcpy(v+%d,m->child_%d.held+%d,%d*sizeof(double));',o,core,child.out_offsets(port),n));
          endif
        case 'Constant',add(sprintf('  memcpy(v+%d,%sp%d,%d*sizeof(double));',o,p,id,n));
        case 'External Input',add(sprintf('  memcpy(v+%d,external+%d,%d*sizeof(double));',o,u.input_offsets(block.value),n));
        case 'Time',add(sprintf('  v[%d]=time;',o));
        case 'Step'
          b=block.value;add(sprintf('  v[%d]=(time<%s||(left&&time==%s))?%s:%s;',o,num(b(1)),num(b(1)),num(b(2)),num(b(3))));
        case 'Rate Transition'
          add(sprintf('  if(hit&&hit[%d]){memcpy(event_model->state+%d,v+%d,%d*sizeof(double));memcpy(v+%d,v+%d,%d*sizeof(double));}',id-1,u.state_offsets(id),u.offsets(sources(1)),n,o,u.offsets(sources(1)),n), ...
            sprintf('  else memcpy(v+%d,state+%d,%d*sizeof(double));',o,u.state_offsets(id),n));
        case {'Unit Delay','Discrete Integrator','Integrator'}
          add(sprintf('  memcpy(v+%d,state+%d,%d*sizeof(double));',o,u.state_offsets(id),n));
        case {'Scope','Inport','Outport'}
          add(sprintf('  memcpy(v+%d,v+%d,%d*sizeof(double));',o,u.offsets(sources(1)),n));
        case {'Saturation','Dead Zone'}
          lo=num(block.value(1));hi=num(block.value(2));
          add(sprintf('  for(size_t i=0;i<%d;++i){const double x=v[%d+i];',n,u.offsets(sources(1))));
          if(strcmp(block.type,'Saturation')), expression=sprintf('x<%s?%s:(x>%s?%s:x)',lo,lo,hi,hi);
          else expression=sprintf('x<%s?x-%s:(x>%s?x-%s:0.0)',lo,lo,hi,hi);endif
          add(sprintf('    v[%d+i]=%s;}',o,expression));
        case 'Switch'
          control=element(u.offsets(sources(2)),u.shapes{sources(2)},u.shapes{id});
          add(sprintf('  for(size_t i=0;i<%d;++i)v[%d+i]=%s>=%s?v[%d+i]:v[%d+i];',n,o,control,num(block.value),u.offsets(sources(1)),u.offsets(sources(3))));
        case {'Gain','Product'}
          if(strcmp(block.type,'Gain')),a=sprintf('%sp%d',p,id);ashape=size(block.value);b=sources(1);
          else a=sprintf('v+%d',u.offsets(sources(1)));ashape=u.shapes{sources(1)};b=sources(2);endif
          bshape=u.shapes{b};add(sprintf('  ob_cc_mul(v+%d,%s,%d,%d,v+%d,%d,%d);',o,a,ashape(1),ashape(2),u.offsets(b),bshape(1),bshape(2)));
        case {'Sum','Function'}
          if(strcmp(block.type,'Sum')),expression='(INPUT_A+INPUT_B)';else expression=u.expressions{id};endif
          expression=strrep(expression,'INPUT_A',element(u.offsets(sources(1)),u.shapes{sources(1)},u.shapes{id}));
          if(numel(sources)>1),expression=strrep(expression,'INPUT_B',element(u.offsets(sources(2)),u.shapes{sources(2)},u.shapes{id}));endif
          add(sprintf('  for(size_t i=0;i<%d;++i)v[%d+i]=%s;',n,o,expression));
      endswitch
    endfor
    if(u.value_count>0),add(sprintf('  for(size_t i=0;i<%s;++i)if(!isfinite(v[i]))return OB_NONFINITE;',cn(u,'VALUE_COUNT')));endif
    add('  return OB_OK;','}');
  endfunction

  function emit_multiple_function(u,id,source)
    proxies=u.edges(u.edges(:,1)==id,2);
    outputs=zeros(1,2);
    for proxy=reshape(proxies,1,[]), outputs(u.flat.blocks(proxy).value)=proxy; endfor
    first=u.offsets(outputs(1)); second=u.offsets(outputs(2));
    shape=u.shapes{source}; input=u.offsets(source); name=u.flat.blocks(id).name;
    if(strcmp(name,'size'))
      add(sprintf('  v[%d]=%s;v[%d]=%s;',first,num(shape(1)),second,num(shape(2))));
      return;
    endif
    if(shape(1)>1), width=shape(2); length=shape(1); stride=1; column_stride=shape(1);
    else width=1; length=shape(2); stride=1; column_stride=0; endif
    if(strcmp(name,'max')),comparison='>';else comparison='<';endif
    add(sprintf('  for(size_t c=0;c<%d;++c){',width), ...
      sprintf('    double best=v[%d+c*%d];size_t index=1;',input,column_stride), ...
      sprintf('    for(size_t r=1;r<%d;++r){const double candidate=v[%d+c*%d+r*%d];',length,input,column_stride,stride), ...
      sprintf('      if(candidate%sbest){best=candidate;index=r+1;}}',comparison), ...
      sprintf('    v[%d+c]=best;v[%d+c]=(double)index;}',first,second));
  endfunction

  function expression=clock_test(ids)
    terms=arrayfun(@(id)sprintf('frame->due[%d]',id-1),ids,'uniformoutput',false);
    if(isempty(terms)),expression='0';else expression=['frame&&(' strjoin(terms,'||') ')'];endif
  endfunction

  function emit_proxy_copies(u,id,child,buffer)
    proxies=u.edges(u.edges(:,1)==id,2);
    for proxy=reshape(proxies,1,[])
      port=u.flat.blocks(proxy).value;
      add(sprintf('    memcpy(v+%d,%s+%d,%d*sizeof(double));',u.offsets(proxy),buffer,child.out_offsets(port),child.out_sizes(port)));
    endfor
  endfunction

  function emit_clock_masks(u,major)
    add(sprintf('  unsigned char hit[%d]={0};',max(1,u.n)));
    for id=reshape(find(strcmp(u.types,'Rate Transition')|strcmp(u.types,'Conditional Subsystem')),1,[])
      if(u.clock_ids(id)>0),condition=sprintf('frame->due[%d]',u.clock_ids(id)-1);
      else condition=major;
        if(!isempty(u.children{id})&&strcmp(u.children{id}.options.mode,'enabled'))
          condition=['(' condition ')||(' clock_test(u.children{id}.all_clocks) ')'];
        endif
      endif
      add(sprintf('  hit[%d]=%s;',id-1,condition));
    endfor
  endfunction

  function emit_clock_commits(u,major)
    for id=reshape(find(strcmp(u.types,'Unit Delay')|strcmp(u.types,'Discrete Integrator')),1,[])
      if(u.clock_ids(id)>0),due=sprintf('frame->due[%d]',u.clock_ids(id)-1);else due=major;endif
      add(sprintf('  if((%s)&&m->pending_valid[%d]){memcpy(m->state+%d,m->pending+%d,%d*sizeof(double));m->pending_valid[%d]=0;}',due,id-1,u.state_offsets(id),u.state_offsets(id),u.sizes(id),id-1));
    endfor
  endfunction

  function emit_clock_captures(u)
    for id=reshape(find((strcmp(u.types,'Unit Delay')|strcmp(u.types,'Discrete Integrator')) & u.clock_ids>0),1,[])
      source=u.edges(u.edges(:,2)==id,1);o=u.state_offsets(id);n=u.sizes(id);
      add(sprintf('  if(frame->due[%d]){',u.clock_ids(id)-1));
      if(strcmp(u.types{id},'Unit Delay'))
        add(sprintf('    memcpy(m->pending+%d,m->value+%d,%d*sizeof(double));',o,u.offsets(source),n));
      else
        add(sprintf('    for(size_t i=0;i<%d;++i)m->pending[%d+i]=m->state[%d+i]+%s*m->value[%d+i];',n,o,o,num(u.flat.sample_times(id,1)),u.offsets(source)));
      endif
      add(sprintf('    for(size_t i=0;i<%d;++i)if(!isfinite(m->pending[%d+i]))return OB_NONFINITE;',n,o),sprintf('    m->pending_valid[%d]=1;}',id-1));
    endfor
  endfunction

  function emit_clocked_child(u)
    p=u.prefix;t=[p 'model'];
    add(sprintf('static int %sclock_process(%s *m,double time,const double *input,int major,double interval,const ob_clock_frame *frame){',p,t), ...
        '  if(!frame)return OB_BAD_ARGUMENT;');
    emit_clock_commits(u,'major');emit_clock_masks(u,'major');
    add(sprintf('  int status=%seval(m,time,m->state,m->value,0,input,hit,m,interval,major?OB_INTERVAL_INHERITED:OB_INTERVAL_ELAPSED,frame);',p), ...
        '  if(status!=OB_OK)return status;');
    emit_clock_captures(u);
    for id=reshape(find(u.clock_ids>0),1,[])
      add(sprintf('  m->tick[%d]=frame->tick[%d]+frame->due[%d];',id-1,u.clock_ids(id)-1,u.clock_ids(id)-1));
    endfor
    add('  if(major)memcpy(m->major_value,m->value,sizeof(m->value));', ...
        '  m->time=time;return OB_OK;}', ...
        sprintf('static int %sclock_init(%s *m,double time,const double *input,int major,const ob_clock_frame *frame){',p,t));
    emit_numeric_init(u);
    add('  m->start_time=frame->origin;', ...
        sprintf('  int status=%sclock_process(m,time,input,major,0.0,frame);',p), ...
        '  if(status==OB_OK){memcpy(m->major_value,m->value,sizeof(m->value));} return status;}', ...
        sprintf('static int %sclock_execute(%s *m,double time,const double *input,int major,double interval,const ob_clock_frame *frame){',p,t), ...
        '  if(!isfinite(time)||time<m->time||(major&&(!isfinite(interval)||interval<=0.0)))return OB_BAD_ARGUMENT;');
    for id=reshape(find((strcmp(u.types,'Unit Delay')|strcmp(u.types,'Discrete Integrator')) & u.clock_ids==0),1,[])
      source=u.edges(u.edges(:,2)==id,1);o=u.state_offsets(id);n=u.sizes(id);
      add('  if(major){');
      if(strcmp(u.types{id},'Unit Delay')),add(sprintf('    memcpy(m->pending+%d,m->major_value+%d,%d*sizeof(double));',o,u.offsets(source),n));
      else add(sprintf('    for(size_t i=0;i<%d;++i)m->pending[%d+i]=m->state[%d+i]+interval*m->major_value[%d+i];',n,o,o,u.offsets(source)));endif
      add(sprintf('    for(size_t i=0;i<%d;++i)if(!isfinite(m->pending[%d+i]))return OB_NONFINITE;',n,o),sprintf('    m->pending_valid[%d]=1;}',id-1));
    endfor
    add(sprintf('  return %sclock_process(m,time,input,major,interval,frame);}',p), ...
