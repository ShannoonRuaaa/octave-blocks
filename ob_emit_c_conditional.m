        '    m->clock_tick[i]+=1.0;double next=ob_clock_time(m,i);', ...
        '    if(!isfinite(next)||next<=previous||next<=time)return OB_BAD_ARGUMENT;}');
    for id=reshape(find(u.clock_ids>0),1,[])
      add(sprintf('  m->tick[%d]=m->clock_tick[%d];',id-1,u.clock_ids(id)-1));
