      add(sprintf('  if(output)hit[%d]=1;',id-1));
    endfor
    add('  int status=ob_eval(m,time,m->state,m->value,0,NULL,hit,m,0.0,0,NULL);if(status!=OB_OK)return status;');
    for id=explicit
      add(sprintf('  if(hit[%d]){',id-1));
