        '    for(size_t i=0;i<OB_CLOCK_COUNT;++i){double hit=ob_clock_time(&work,i);', ...
        '      if(!isfinite(hit)||hit<=start)return OB_BAD_ARGUMENT;', ...
        '      if(hit<end&&!ob_clock_close(hit,next_time,work.start_time))end=hit;}', ...
        '    const double scheduled_end=end;');
    if(u.has_continuous)
      emit_tree_boundaries(u,'work.','1');
      if(u.input_count>0),add('    status=ob_next_input_boundary(&work,start,&end);if(status!=OB_OK)return status;');endif
      add('    status=ob_integrate_shared(&work,start,end);if(status!=OB_OK)return status;');
    else
      add('    status=ob_eval(&work,end,work.state,work.value,1,NULL,NULL,&work,0.0,0,NULL);if(status!=OB_OK)return status;');
    endif
    add('    if(!isfinite(end)||end<=start)return OB_BAD_ARGUMENT;', ...
        '    if(end==scheduled_end){const int output=end==next_time;status=ob_process_hits(&work,end,output,output);if(status!=OB_OK)return status;}', ...
        '    else {work.time=end;}start=end;', ...
        '  }*model=work;return OB_OK;}');
  endfunction

  function emit_root(u)
    rates=u.flat.sample_times;explicit=reshape(find(rates(:,1)'>0),1,[]);
    delayed=reshape(find(strcmp(u.types,'Unit Delay')|strcmp(u.types,'Discrete Integrator')),1,[]);
    inherited=delayed(rates(delayed,1)==0);
    continuous=reshape(find(strcmp(u.types,'Integrator')),1,[]);
    if(!isempty(explicit))
      add('static int ob_time_close(double a,double b,double origin){', ...
        sprintf('  return isfinite(a)&&isfinite(b)&&fabs(a-b)<=fmin(%s,8.0*DBL_EPSILON*fmax(DBL_MIN,fmax(fabs(origin),fmax(fabs(a),fabs(b)))));}',num(min(rates(explicit,1))/16)), ...
        'static double ob_tick_time(const ob_model *m,size_t b){return m->start_time+ob_sample_offset[b]+m->tick[b]*ob_sample_period[b];}');
    endif
    add('static int ob_process_hits(ob_model *m,double time,int output,int commit){', ...
      '  unsigned char hit[OB_BLOCK_COUNT]={0};(void)output;(void)commit;');
