        add(sprintf('    m->pending_valid[%d]=1;',id-1),sprintf('    for(size_t i=0;i<%d;++i)if(!isfinite(m->pending[%d+i]))return OB_NONFINITE;',n,o));
      endif
      add(sprintf('    double previous=ob_tick_time(m,%d);if(m->tick[%d]>=9007199254740991.0)return OB_BAD_ARGUMENT;',id-1,id-1), ...
        sprintf('    m->tick[%d]+=1.0;double next=ob_tick_time(m,%d);',id-1,id-1), ...
        '    if(!isfinite(next)||next<=previous||next<=time)return OB_BAD_ARGUMENT;','  }');
    endfor
    add('  m->time=time;return OB_OK;}');
    add('int ob_model_outputs(ob_model *m){double v[OB_VALUE_STORAGE];', ...
      '  if(!m||!m->initialized||!isfinite(m->time))return OB_BAD_ARGUMENT;', ...
      '  int status=ob_eval(m,m->time,m->state,v,0,NULL,NULL,NULL,0.0,0,NULL);', ...
      '  if(status==OB_OK){memcpy(m->value,v,OB_VALUE_COUNT*sizeof(double));} return status;}', ...
      'int ob_model_set_input_provider(ob_model *m,ob_input_provider provider,ob_input_event event,void *user){', ...
      '  if(!m||!m->initialized||(!provider&&(event||user))||(OB_INPUT_PORT_COUNT==0&&provider))return OB_BAD_ARGUMENT;', ...
      '  ob_model work=*m;work.input_provider=provider;work.input_event=event;work.input_user=user;', ...
      '  int status=ob_model_outputs(&work);if(status==OB_OK)*m=work;return status;}', ...
      'int ob_model_init_inputs(ob_model *model,double time,ob_input_provider provider,ob_input_event event,void *user){', ...
      '  if(!model||!isfinite(time)||(!provider&&(event||user))||(OB_INPUT_PORT_COUNT==0&&provider))return OB_BAD_ARGUMENT;', ...
      '  ob_model work;memset(&work,0,sizeof(work));ob_model *m=&work;', ...
      '  m->input_provider=provider;m->input_event=event;m->input_user=user;');
    emit_numeric_init(u);
    for id=explicit
      add(sprintf('  if(!isfinite(time+ob_sample_period[%d])||time+ob_sample_period[%d]<=time)return OB_BAD_ARGUMENT;',id-1,id-1), ...
        sprintf('  const double first%d=ob_tick_time(m,%d);',id,id-1), ...
        sprintf('  if(!isfinite(first%d)||first%d<time||(ob_sample_offset[%d]>0.0&&first%d<=time))return OB_BAD_ARGUMENT;',id,id,id-1,id));
    endfor
    add('  int status=ob_process_hits(m,time,1,0);if(status==OB_OK)*model=work;return status;}', ...
      'int ob_model_init(ob_model *m,double time){return ob_model_init_inputs(m,time,NULL,NULL,NULL);}');
    if(u.has_continuous_children),emit_shared_integrator(u);
    elseif(!isempty(continuous)),emit_integrator(u,continuous);endif
    add('int ob_model_step(ob_model *model,double next_time){', ...
      '  if(!model||!model->initialized||!isfinite(next_time)||next_time<=model->time)return OB_BAD_ARGUMENT;', ...
      '  double dt=next_time-model->time;if(!isfinite(dt))return OB_BAD_ARGUMENT;', ...
      '  ob_model work=*model;int status=ob_model_outputs(&work);if(status!=OB_OK)return status;');
    for id=inherited
      source=u.edges(u.edges(:,2)==id,1);o=u.state_offsets(id);n=u.sizes(id);
      if(strcmp(u.types{id},'Unit Delay')),add(sprintf('  memcpy(work.pending+%d,work.value+%d,%d*sizeof(double));',o,u.offsets(source),n));
      else add(sprintf('  for(size_t i=0;i<%d;++i)work.pending[%d+i]=work.state[%d+i]+dt*work.value[%d+i];',n,o,o,u.offsets(source)));endif
      add(sprintf('  work.pending_valid[%d]=1;',id-1),sprintf('  for(size_t i=0;i<%d;++i)if(!isfinite(work.pending[%d+i]))return OB_NONFINITE;',n,o));
    endfor
    add('  double start=work.time;while(start<next_time){double end=next_time;');
    for id=explicit
      add(sprintf('    double tick%d=ob_tick_time(&work,%d);if(!isfinite(tick%d)||tick%d<=start)return OB_BAD_ARGUMENT;',id,id-1,id,id), ...
        sprintf('    if(tick%d<end&&!ob_time_close(tick%d,next_time,work.start_time))end=tick%d;',id,id,id));
    endfor
    add('    const double scheduled_end=end;');
    if(u.has_continuous)
      if(u.has_continuous_children),emit_tree_boundaries(u,'work.','1');
      else
        for id=reshape(find(strcmp(u.types,'Step')),1,[])
          time=num(u.flat.blocks(id).value(1));add(sprintf('    if(%s>start&&%s<end)end=%s;',time,time,time));
        endfor
      endif
      if(u.input_count>0),add('    status=ob_next_input_boundary(&work,start,&end);if(status!=OB_OK)return status;');endif
      if(u.has_continuous_children),add('    status=ob_integrate_shared(&work,start,end);if(status!=OB_OK)return status;');
      else add('    status=ob_integrate(&work,start,end,work.state);if(status!=OB_OK)return status;');endif
    endif
    add('    if(!isfinite(end)||end<=start){return OB_BAD_ARGUMENT;} const int output=end==next_time;', ...
      '    if(end==scheduled_end){status=ob_process_hits(&work,end,output,output);if(status!=OB_OK)return status;}', ...
      '    else {work.time=end;} start=end;', '  }*model=work;return OB_OK;}');
  endfunction

  function emit_tree_boundaries(u,access,enabled)
    for id=reshape(find(strcmp(u.types,'Step')),1,[])
      time=num(u.flat.blocks(id).value(1));
      add(sprintf('    if((%s)&&%s>start&&%s<end)end=%s;',enabled,time,time,time));
    endfor
    for id=1:u.n
      child=u.children{id};
      if(!isempty(child)&&(child.has_continuous||(clock_mode&&child.clocked)))
        next=sprintf('%schild_%d.',access,id);
        guard=sprintf('(%s)&&%sinitialized&&%swas_enabled',enabled,next,next);
        emit_tree_boundaries(child,next,guard);
      endif
    endfor
  endfunction

  function emit_shared_integrator(u)
    entries=continuous_entries(u,'','1');
    count=sum([entries.size]);
    add(sprintf('enum { OB_CONTINUOUS_COUNT=%d };',count), ...
        'static int ob_shared_rhs(ob_model *m,double time,double *dy,int left){', ...
        '  int status=ob_eval(m,time,m->state,m->value,left,NULL,NULL,m,0.0,0,NULL);', ...
        '  if(status!=OB_OK){return status;} memset(dy,0,OB_CONTINUOUS_COUNT*sizeof(double));');
    offset=0;
    for e=entries
      add(sprintf('  if(%s)memcpy(dy+%d,m->%svalue+%d,%d*sizeof(double));',e.guard,offset,e.access,e.source,e.size));
      offset+=e.size;
    endfor
    add('  return OB_OK;}', ...
        'static int ob_integrate_shared(ob_model *m,double start,double end){', ...
        '  ob_model base=*m,stage;double k1[OB_CONTINUOUS_COUNT],k2[OB_CONTINUOUS_COUNT],k3[OB_CONTINUOUS_COUNT],k4[OB_CONTINUOUS_COUNT];', ...
        '  const double h=end-start;stage=base;int status=ob_shared_rhs(&stage,start,k1,0);if(status!=OB_OK)return status;');
    for phase=1:3
      add('  stage=base;');offset=0;
      if(phase==3),scale='h';time='end';left=1;else scale='h/2.0';time='start+h/2.0';left=0;endif
      for e=entries
        add(sprintf('  for(size_t i=0;i<%d;++i)stage.%sstate[%d+i]=base.%sstate[%d+i]+%s*k%d[%d+i];', ...
            e.size,e.access,e.state,e.access,e.state,scale,phase,offset));
        offset+=e.size;
      endfor
      add(sprintf('  status=ob_shared_rhs(&stage,%s,k%d,%d);if(status!=OB_OK)return status;',time,phase+1,left));
    endfor
    offset=0;
    for e=entries
      add(sprintf('  for(size_t i=0;i<%d;++i)m->%sstate[%d+i]+=h/6.0*(k1[%d+i]+2.0*k2[%d+i]+2.0*k3[%d+i]+k4[%d+i]);', ...
          e.size,e.access,e.state,offset,offset,offset,offset));
      offset+=e.size;
    endfor
    add('  return ob_eval(m,end,m->state,m->value,1,NULL,NULL,m,0.0,0,NULL);','}');
  endfunction

  function entries=continuous_entries(u,access,guard)
    entries=struct('access',{},'guard',{},'state',{},'source',{},'size',{});
    for id=reshape(find(strcmp(u.types,'Integrator')),1,[])
      source=u.edges(u.edges(:,2)==id,1);
      entries(end+1)=struct('access',access,'guard',guard,'state',u.state_offsets(id), ...
          'source',u.offsets(source),'size',u.sizes(id));
    endfor
    for id=1:u.n
      child=u.children{id};
      if(!isempty(child)&&child.has_continuous)
        next=sprintf('%schild_%d.',access,id);
        active=sprintf('(%s)&&m->%sinitialized&&m->%swas_enabled',guard,next,next);
        entries=[entries continuous_entries(child,next,active)];
      endif
    endfor
  endfunction

  function emit_integrator(u,ids)
    add('static int ob_rhs(const ob_model *m,double time,const double *state,double *dy,int left){', ...
      '  double v[OB_VALUE_STORAGE];int status=ob_eval(m,time,state,v,left,NULL,NULL,NULL,0.0,0,NULL);', ...
      '  if(status!=OB_OK){return status;} memset(dy,0,OB_STATE_STORAGE*sizeof(double));');
    for id=ids
      source=u.edges(u.edges(:,2)==id,1);add(sprintf('  memcpy(dy+%d,v+%d,%d*sizeof(double));',u.state_offsets(id),u.offsets(source),u.sizes(id)));
    endfor
    add('  return OB_OK;}', ...
      'static int ob_integrate(const ob_model *m,double start,double end,double *state){', ...
      '  double k1[OB_STATE_STORAGE],k2[OB_STATE_STORAGE],k3[OB_STATE_STORAGE],k4[OB_STATE_STORAGE],stage[OB_STATE_STORAGE];', ...
      '  double h=end-start;int status=ob_rhs(m,start,state,k1,0);if(status!=OB_OK)return status;', ...
      '  for(size_t i=0;i<OB_STATE_COUNT;++i)stage[i]=state[i]+h/2.0*k1[i];', ...
      '  status=ob_rhs(m,start+h/2.0,stage,k2,0);if(status!=OB_OK)return status;', ...
      '  for(size_t i=0;i<OB_STATE_COUNT;++i)stage[i]=state[i]+h/2.0*k2[i];', ...
      '  status=ob_rhs(m,start+h/2.0,stage,k3,0);if(status!=OB_OK)return status;', ...
      '  for(size_t i=0;i<OB_STATE_COUNT;++i)stage[i]=state[i]+h*k3[i];', ...
      '  status=ob_rhs(m,end,stage,k4,1);if(status!=OB_OK)return status;', ...
      '  for(size_t i=0;i<OB_STATE_COUNT;++i)state[i]+=h/6.0*(k1[i]+2.0*k2[i]+2.0*k3[i]+k4[i]);', ...
      '  return OB_OK;}');
  endfunction
endfunction

function name=cn(u,key)
  if(u.root),name=['OB_' key];else name=[u.prefix key];endif
endfunction
function yes=has_multiply(u)
  yes=any(ismember(u.types,{'Gain','Product'}));
  for child=u.children,if(!isempty(child{1})),yes|=has_multiply(child{1});endif;endfor
endfunction
function text=num(value)
  text=sprintf('%.17g',value);
  if(isempty(strfind(text,'.'))&&isempty(strfind(lower(text),'e'))),text=[text '.0'];endif
endfunction
function text=nums(values)
  text=strjoin(arrayfun(@num,values,'uniformoutput',false),',');
endfunction
function text=ints(values)
  if(isempty(values)),text='0';else text=sprintf('%d,',values);text(end)=[];endif
endfunction
function text=element(offset,shape,out)
  if(isequal(shape,out)),text=sprintf('v[%d+i]',offset);
  elseif(prod(shape)==1),text=sprintf('v[%d]',offset);
  else
    row='0';column='0';if(shape(1)!=1),row=sprintf('(i%%%d)',out(1));endif
    if(shape(2)!=1),column=sprintf('(i/%d)',out(1));endif
    text=sprintf('v[%d+%s+%s*%d]',offset,row,column,shape(1));
  endif
endfunction
