      add(sprintf('  if(commit&&m->pending_valid[%d]){memcpy(m->state+%d,m->pending+%d,%d*sizeof(double));m->pending_valid[%d]=0;}',id-1,u.state_offsets(id),u.state_offsets(id),u.sizes(id),id-1));
    endfor
