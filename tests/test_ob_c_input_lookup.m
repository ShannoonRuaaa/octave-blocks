function test_ob_c_input_lookup (directory)
  test_path_cleanup = ob_test_setup ();
  % Emit an independently compiled C99 oracle test for generated input helpers.
  % Test-CInputLookup.ps1 compiles and runs both continuous/discrete variants.
  if (! exist(directory,'dir')), mkdir(directory); endif
  inputs = {ob_input_signal([-4;0;3;8],[10 11 12 13;20 21 22 23;30 31 32 33;40 41 42 43],[2 2]), ...
            ob_input_signal([-5;1;7],[100 101;200 201;300 301],[2 1],'linear'), ...
            ob_input_signal(2,[901 902],[1 2]), ...
            ob_input_signal([-2;8],[501;601],[1 1],'linear')};
  prefix = {'#include <float.h>', '#include <math.h>', '#include <stdint.h>', ...
    '#include <stdio.h>', '#include <stdlib.h>', '#include <string.h>', ...
    '#include <time.h>', ...
    'enum { OB_OK = 0, OB_INPUT_ERROR = 1, OB_NONFINITE = 2 };', ...
    '#define OB_INPUT_VALUE_COUNT 9', ...
    'typedef int (*input_fn)(double, int, double *, size_t, void *);', ...
    'typedef double (*event_fn)(double, double, void *);', ...
    'typedef struct { input_fn input_provider; event_fn input_event; void *input_user; } ob_model;'};
  for continuous = [false true]
    name = sprintf('c-input-lookup-%d.c',continuous);
    lines = [prefix {sprintf('#define LOOKUP_CONTINUOUS %d',continuous)} ...
             ob_c_input_lines(inputs,continuous) reshape(harness(),1,[])];
    fid = fopen(fullfile(directory,name),'w');
    assert(fid >= 0,'Cannot write input lookup harness');
    unwind_protect
      fprintf(fid,'%s\n',lines{:});
    unwind_protect_cleanup
      fclose(fid);
    end_unwind_protect
  endfor
  fprintf('Prepared continuous/discrete C input lookup oracle harnesses\n');
endfunction

function lines = harness ()
  lines = {
'/* Independent pre-change linear scans are the correctness oracle. */'
'static size_t reference_upper(const double *t, size_t n, double x) {'
'  size_t i = 0;'
'  while (i < n && t[i] <= x) ++i;'
'  return i;'
'}'
'static void reference_sample(const double *t, const double *v, size_t n,'
'                             size_t c, int linear, double x, int left, double *out) {'
'  size_t row = 0;'
'  while (row + 1 < n && x >= t[row + 1]) ++row;'
'  if (!linear) {'
'    if (left && row > 0 && x == t[row]) --row;'
'    memcpy(out, v + row*c, c*sizeof(double));'
'  } else if (x <= t[0] || row + 1 == n) {'
'    memcpy(out, v + row*c, c*sizeof(double));'
'  } else {'
'    const double w = (x-t[row])/(t[row+1]-t[row]);'
'    for (size_t i = 0; i < c; ++i) out[i] = (1.0-w)*v[row*c+i] + w*v[(row+1)*c+i];'
'  }'
'}'
'static size_t checks = 0;'
'static void require(int ok, const char *reason) {'
'  if (!ok) { fprintf(stderr, "FAIL: %s (check %zu)\n", reason, checks); exit(1); }'
'  ++checks;'
'}'
'static uint32_t rng = UINT32_C(405317);'
'static double random_unit(void) {'
'  rng = rng*UINT32_C(1664525) + UINT32_C(1013904223);'
'  return (double)rng/4294967296.0;'
'}'
'static void check_query(const double *t, const double *v, size_t n, double x) {'
'  double actual[4], expected[4];'
'  const size_t i = ob_input_upper_bound(t,n,x);'
'  require(i == reference_upper(t,n,x), "first strictly later knot");'
'  require(i <= n && (i == n || t[i] > x), "bounded later-knot index");'
'  for (int linear = 0; linear <= 1; ++linear) {'
'    for (int left = 0; left <= 1; ++left) {'
'      ob_sample_input(t,v,n,4,linear,x,left,actual);'
'      reference_sample(t,v,n,4,linear,x,left,expected);'
'      for (size_t j = 0; j < 4; ++j) require(actual[j] == expected[j], "sample matches linear oracle");'
'    }'
'  }'
'}'
'static void check_knots(const double *t, const double *v, size_t n) {'
'  const size_t stride = n > 1000 ? n/127 : 1;'
'  check_query(t,v,n,-DBL_MAX); check_query(t,v,n,DBL_MAX);'
'  for (size_t i = 0; i < n; i += stride) {'
'    check_query(t,v,n,nextafter(t[i],-INFINITY));'
'    check_query(t,v,n,t[i]);'
'    check_query(t,v,n,nextafter(t[i],INFINITY));'
'  }'
'  check_query(t,v,n,t[n-1]);'
'  check_query(t,v,n,nextafter(t[n-1],-INFINITY));'
'  check_query(t,v,n,nextafter(t[n-1],INFINITY));'
'}'
'static void check_dynamic_tables(void) {'
'  const size_t sizes[] = {1,2,3,16,1000,100000};'
'  for (size_t k = 0; k < sizeof(sizes)/sizeof(sizes[0]); ++k) {'
'    const size_t n = sizes[k];'
'    double *t = malloc(n*sizeof(double)), *v = malloc(4*n*sizeof(double));'
'    require(t && v, "table allocation");'
'    t[0] = -7.0;'
'    for (size_t i = 0; i < n; ++i) {'
'      if (i) t[i] = t[i-1] + 0.01 + random_unit();'
'      for (size_t j = 0; j < 4; ++j) v[4*i+j] = 200.0*random_unit()-100.0;'
'    }'
'    check_knots(t,v,n);'
'    for (size_t i = 0; i < 257; ++i) check_query(t,v,n,t[0]-1.0+random_unit()*(t[n-1]-t[0]+2.0));'
'    free(v); free(t);'
'  }'
'  {'
'    const double huge[] = {-DBL_MAX,-DBL_MAX/2.0,0.0,DBL_MAX/2.0,DBL_MAX};'
'    const double tiny = nextafter(0.0,1.0);'
'    const double small[] = {-DBL_MIN,-tiny,0.0,tiny,DBL_MIN};'
'    double nearby[5], v[20];'
'    nearby[0] = 1e300;'
'    for (size_t i = 1; i < 5; ++i) nearby[i] = nextafter(nearby[i-1],INFINITY);'
'    for (size_t i = 0; i < 20; ++i) v[i] = (double)i - 3.0;'
'    check_knots(huge,v,5); check_knots(small,v,5); check_knots(nearby,v,5);'
'  }'
'}'
'static void reference_inputs(double t, int left, double *out) {'
'  reference_sample(ob_input_t1,ob_input_v1,4,4,0,t,left,out);'
'  reference_sample(ob_input_t2,ob_input_v2,3,2,1,t,left,out+4);'
'  reference_sample(ob_input_t3,ob_input_v3,1,2,0,t,left,out+6);'
'  reference_sample(ob_input_t4,ob_input_v4,2,1,1,t,left,out+8);'
'}'
'#if LOOKUP_CONTINUOUS'
'static double reference_boundary(double after, double before) {'
'  const double *tables[] = {ob_input_t1,ob_input_t2,ob_input_t3,ob_input_t4};'
'  const size_t rows[] = {4,3,1,2};'
'  for (size_t port = 0; port < 4; ++port)'
'    for (size_t i = 0; i < rows[port]; ++i)'
'      if (tables[port][i] > after && tables[port][i] < before) before = tables[port][i];'
'  return before;'
'}'
'#endif'
'static void check_generated_ports(void) {'
'  const double knots[] = {-5,-4,-2,0,1,2,3,7,8};'
'  const double packed[] = {10,11,12,13,100,101,901,902,501};'
'  ob_model model = {NULL,NULL,NULL};'
'  double out[9], expected[9];'
'  require(ob_read_inputs(&model,-DBL_MAX,0,out) == OB_OK, "read first rows");'
'  for (size_t j = 0; j < 9; ++j) require(out[j] == packed[j], "multiport row-major samples and component packing");'
'  for (size_t k = 0; k < sizeof(knots)/sizeof(knots[0]) + 256; ++k) {'
'    const double knot = k < sizeof(knots)/sizeof(knots[0]) ? knots[k] : -10.0 + 25.0*random_unit();'
'    const double times[] = {nextafter(knot,-INFINITY),knot,nextafter(knot,INFINITY)};'
'    for (size_t q = 0; q < 3; ++q) {'
'      const double t = times[q];'
'      for (int left = 0; left <= 1; ++left) {'
'        require(ob_read_inputs(&model,t,left,out) == OB_OK, "read sampled multiport values");'
'        reference_inputs(t,left,expected);'
'        for (size_t j = 0; j < 9; ++j) require(out[j] == expected[j], "generated port matches oracle");'
'      }'
'#if LOOKUP_CONTINUOUS'
'      {'
'        const double limits[] = {t,nextafter(t,INFINITY),t+0.5,t+20.0,DBL_MAX};'
'        for (size_t j = 0; j < sizeof(limits)/sizeof(limits[0]); ++j) {'
'          double before = limits[j];'
'          require(ob_next_input_boundary(&model,t,&before) == OB_OK, "sampled boundary status");'
'          require(before == reference_boundary(t,limits[j]), "sampled boundary matches scan across all ports");'
'        }'
'      }'
'#endif'
'    }'
'  }'
'  require(ob_read_inputs(&model,8.0,1,out) == OB_OK && out[0] == 30.0 && out[8] == 601.0, "ZOH final left-limit and linear exact endpoint");'
'  require(ob_read_inputs(&model,8.0,0,out) == OB_OK && out[0] == 40.0, "ZOH exact final right value");'
'#if LOOKUP_CONTINUOUS'
'  {'
'    double before = DBL_MAX;'
'    require(ob_next_input_boundary(&model,-DBL_MAX,&before) == OB_OK && before == -5.0, "first boundary from minimum finite time");'
'    before = DBL_MAX;'
'    require(ob_next_input_boundary(&model,DBL_MAX,&before) == OB_OK && before == DBL_MAX, "boundary sentinel at maximum finite time");'
'  }'
'#endif'
'}'
'static int provider(double t, int left, double *out, size_t count, void *user) {'
'  const int mode = *(int *)user;'
'  if (count != 9) return OB_INPUT_ERROR;'
'  if (mode == 1) return 99;'
'  for (size_t i = 0; i < count - (mode == 2 ? 1 : 0); ++i) out[i] = t + (double)i + left;'
'  if (mode == 3) out[3] = INFINITY;'
'  return OB_OK;'
'}'
'#if LOOKUP_CONTINUOUS'
'static double event_provider(double after, double before, void *user) {'
'  switch (*(int *)user) {'
'    case 1: return after; case 2: return nextafter(after,-INFINITY);'
'    case 3: return nextafter(before,INFINITY); case 4: return NAN;'
'    case 5: return INFINITY; case 6: return before; default: return after + 0.25;'
'  }'
'}'
'#endif'
'static void check_providers(void) {'
'  int mode = 0;'
'  double out[9];'
'  ob_model model = {provider,NULL,&mode};'
'  require(ob_read_inputs(&model,17.0,1,out) == OB_OK, "host provider success");'
'  for (size_t i = 0; i < 9; ++i) require(out[i] == 18.0 + i, "host bypass and left flag");'
'  mode = 1; require(ob_read_inputs(&model,0,0,out) == OB_INPUT_ERROR, "host provider status mapping");'
'  mode = 2; require(ob_read_inputs(&model,0,0,out) == OB_NONFINITE, "host partial write rejected");'
'  mode = 3; require(ob_read_inputs(&model,0,0,out) == OB_NONFINITE, "host nonfinite value rejected");'
'#if LOOKUP_CONTINUOUS'
'  {'
'    double before = 20;'
'    require(ob_next_input_boundary(&model,0,&before) == OB_OK && before == 20, "host provider without event bypasses sampled knots");'
'    model.input_event = event_provider; mode = 0; before = 20;'
'    require(ob_next_input_boundary(&model,10,&before) == OB_OK && before == 10.25, "host event success");'
'    for (mode = 1; mode <= 5; ++mode) {'
'      before = 20;'
'      require(ob_next_input_boundary(&model,10,&before) == OB_INPUT_ERROR && before == 20, "invalid host event leaves boundary unchanged");'
'    }'
'    mode = 6; before = 20;'
'    require(ob_next_input_boundary(&model,10,&before) == OB_OK && before == 20, "host event at supplied limit accepted");'
'    model.input_provider = NULL; mode = 4; before = 20;'
'    require(ob_next_input_boundary(&model,0,&before) == OB_OK && before == 1, "event callback ignored without input provider");'
'  }'
'#endif'
'}'
'/* Optional lookup-only microbenchmark; excludes generation/integration costs.'
' * Timer resolution, compiler, cache, query order and size affect results.'
' * Neither universal speedup nor zero overhead for small tables is asserted. */'
'static void benchmark(void) {'
'  const size_t sizes[] = {16,1000,100000};'
'  volatile size_t sink = 0;'
'  puts("rows,queries,binary_seconds,linear_seconds");'
'  for (size_t k = 0; k < 3; ++k) {'
'    const size_t n = sizes[k], queries = 20000000/n + 10000;'
'    double *t = malloc(n*sizeof(double));'
'    clock_t start; double binary, linear;'
'    require(t != NULL, "benchmark allocation");'
'    for (size_t i = 0; i < n; ++i) t[i] = (double)i;'
'    start = clock();'
'    for (size_t i = 0; i < queries; ++i) sink += ob_input_upper_bound(t,n,(double)(i%1024)*(double)(n-1)/1023.0);'
'    binary = (double)(clock()-start)/CLOCKS_PER_SEC;'
'    start = clock();'
'    for (size_t i = 0; i < queries; ++i) sink += reference_upper(t,n,(double)(i%1024)*(double)(n-1)/1023.0);'
'    linear = (double)(clock()-start)/CLOCKS_PER_SEC;'
'    printf("%zu,%zu,%.6f,%.6f\n",n,queries,binary,linear);'
'    free(t);'
'  }'
'  if (sink == 0) puts("unreachable benchmark sink");'
'}'
'int main(int argc, char **argv) {'
'  check_dynamic_tables(); check_generated_ports(); check_providers();'
'  printf("C input lookup passed: %zu checks, continuous=%d\n",checks,LOOKUP_CONTINUOUS);'
'  if (argc > 1 && strcmp(argv[1],"--benchmark") == 0) benchmark();'
'  return 0;'
'}'
};
endfunction
