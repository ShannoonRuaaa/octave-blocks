function lines = ob_emit_c_event_root (root)
  % Accepted event scheduling is kept separate from pure, frozen-mode trials.
  lines = {};
  clocks = numel(root.clock_inventory);
  guards = root.event_inventory;
  delayed = reshape(find(strcmp(root.types,'Unit Delay') | strcmp(root.types,'Discrete Integrator')),1,[]);
  inherited = delayed(root.clock_ids(delayed)==0);
  entries = continuous_entries(root,'','1');
  count = sum([entries.size]);
  add('static const unsigned char ob_event_no_due[OB_CLOCK_STORAGE]={0};', ...
      'static const double ob_event_no_tick[OB_CLOCK_STORAGE]={0.0};', ...
      'static int ob_event_evaluate(ob_model *m,double time,int left,const int *mode){', ...
      '  const ob_clock_frame frame={m->start_time,ob_event_no_due,ob_event_no_tick,mode,0,0};', ...
      '  return ob_eval(m,time,m->state,m->value,left,NULL,NULL,m,0.0,OB_INTERVAL_ELAPSED,&frame);}', ...
      'static int ob_event_collect(const ob_model *m,ob_event_snapshot *snapshot){', ...
      '  (void)m;memset(snapshot,0,sizeof(*snapshot));');
  for index=1:numel(guards)
    g=guards(index); [access,active]=guard_access(root,g.compiled_path);
    slot=g.mode_id-1; source=g.source_offset;
    add(sprintf('  if(%s){const double value=m->%svalue[%d]-(%s);',active,access,source,num(g.boundary)), ...
        sprintf('    if(!isfinite(value)){return OB_NONFINITE;}snapshot->active[%d]=1;snapshot->value[%d]=value;',index-1,index-1));
    if(strcmp(g.side,'control'))
      child=sprintf('%schild_%d.',access,g.block_id);
      add(sprintf('    snapshot->mode[%d]=value==0.0?m->%scontrol_sign:ob_event_sign(value);}',slot,child));
    elseif(strcmp(g.side,'threshold'))
      add(sprintf('    snapshot->mode[%d]=value>=0.0;}',slot));
    elseif(strcmp(g.side,'lower'))
      block=unit_at(root,g.compiled_path(1:end-1)).flat.blocks(g.block_id);
      add(sprintf('    snapshot->mode[%d]=value<0.0?-1:(m->%svalue[%d]>%s?1:0);}',slot,access,source,num(block.value(2))));
    else
      % The lower descriptor already assigned the shared regime.
      add('  }');
    endif
  endfor
  add('  return OB_OK;}', ...
      'static int ob_event_snapshot_at(ob_model *m,double time,int left,const int *mode,ob_event_snapshot *snapshot){', ...
      '  int status=ob_event_evaluate(m,time,left,mode);if(status!=OB_OK)return status;', ...
      '  return ob_event_collect(m,snapshot);}', ...
      sprintf('enum { OB_CONTINUOUS_COUNT=%d,OB_CONTINUOUS_STORAGE=%d };',count,max(1,count)), ...
      'static int ob_event_rhs(ob_model *m,double time,double *dy,int left,const int *mode){', ...
      '  int status=ob_event_evaluate(m,time,left,mode);if(status!=OB_OK)return status;', ...
      '  memset(dy,0,OB_CONTINUOUS_STORAGE*sizeof(double));');
  offset=0;
  for e=entries
    add(sprintf('  if(%s)memcpy(dy+%d,m->%svalue+%d,%d*sizeof(double));',e.guard,offset,e.access,e.source,e.size));
    offset+=e.size;
  endfor
  add('  return OB_OK;}', ...
      'static int ob_event_flow(const ob_model *origin,double begin,double finish,int left,const int *mode,ob_model *result){', ...
      '  const double h=finish-begin;ob_model stage;double k1[OB_CONTINUOUS_STORAGE],k2[OB_CONTINUOUS_STORAGE],k3[OB_CONTINUOUS_STORAGE],k4[OB_CONTINUOUS_STORAGE];', ...
      '  if(!isfinite(h)||h<0.0)return OB_BAD_ARGUMENT;', ...
      '  *result=*origin;if(h==0.0)return ob_event_evaluate(result,finish,left,mode);', ...
      '  stage=*origin;int status=ob_event_rhs(&stage,begin,k1,0,mode);if(status!=OB_OK)return status;');
  for phase=1:3
    add('  stage=*origin;');offset=0;
    if(phase==3),scale='h';time='finish';endpoint='left';else scale='h/2.0';time='begin+h/2.0';endpoint='0';endif
    for e=entries
      add(sprintf('  for(size_t i=0;i<%d;++i)stage.%sstate[%d+i]=origin->%sstate[%d+i]+%s*k%d[%d+i];',e.size,e.access,e.state,e.access,e.state,scale,phase,offset));offset+=e.size;
    endfor
    add(sprintf('  status=ob_event_rhs(&stage,%s,k%d,%s,mode);if(status!=OB_OK)return status;',time,phase+1,endpoint));
  endfor
  offset=0;
  for e=entries
    add(sprintf('  for(size_t i=0;i<%d;++i){result->%sstate[%d+i]=origin->%sstate[%d+i]+h/6.0*(k1[%d+i]+2.0*k2[%d+i]+2.0*k3[%d+i]+k4[%d+i]);',e.size,e.access,e.state,e.access,e.state,offset,offset,offset,offset), ...
        sprintf('    if(!isfinite(result->%sstate[%d+i]))return OB_NONFINITE;}',e.access,e.state));offset+=e.size;
  endfor
  add('  result->time=finish;return ob_event_evaluate(result,finish,left,mode);}', ...
      'static int ob_event_settle(ob_model *m,double begin,double finish,int *mode,ob_event_snapshot *at){', ...
      '  int status=ob_event_snapshot_at(m,begin,0,NULL,at);if(status!=OB_OK)return status;', ...
      '  memcpy(mode,at->mode,OB_EVENT_STORAGE*sizeof(int));', ...
      '  unsigned char active[OB_EVENT_STORAGE];memcpy(active,at->active,sizeof(active));', ...
      '  for(size_t iteration=0;iteration<2*OB_EVENT_STORAGE+16;++iteration){', ...
      '    status=ob_event_snapshot_at(m,begin,0,mode,at);if(status!=OB_OK)return status;', ...
      '    if(memcmp(active,at->active,sizeof(active))!=0)return OB_EVENT_ERROR;', ...
      '    int proposed[OB_EVENT_STORAGE];', ...
      '    if(ob_event_prepare_proposed(at,mode,proposed)){', ...
      '      const double width=fmin((finish-begin)/1024.0,sqrt(DBL_EPSILON)*fmax(1.0,fabs(begin)));', ...
      '      double probe_time=fmin(finish,begin+width);if(probe_time<=begin)probe_time=nextafter(begin,finish);', ...
      '      if(probe_time<=begin||probe_time>finish)return OB_EVENT_ERROR;', ...
      '      ob_model trial;ob_event_snapshot probe;', ...
      '      status=ob_event_flow(m,begin,probe_time,0,proposed,&trial);if(status!=OB_OK)return status;', ...
      '      status=ob_event_collect(&trial,&probe);if(status!=OB_OK)return status;', ...
      '      if(!ob_event_same_layout(at,&probe))return OB_EVENT_ERROR;', ...
      '      ob_event_apply_probe(at,&probe,proposed);', ...
      '    }', ...
      '    if(memcmp(mode,proposed,OB_EVENT_STORAGE*sizeof(int))==0)return OB_OK;', ...
      '    memcpy(mode,proposed,OB_EVENT_STORAGE*sizeof(int));', ...
      '  }return OB_EVENT_ERROR;}', ...
      'static int ob_event_one_crossed(size_t i,const ob_event_snapshot *before,const ob_event_snapshot *after,const int *mode){', ...
      '  if(!before->active[i]||!after->active[i])return 0;', ...
      '  const double a=before->value[i],b=after->value[i];', ...
      '  if((a<0.0&&b>=0.0)||(a>0.0&&b<=0.0))return 1;', ...
      '  return a==0.0&&b!=0.0&&((ob_event_kind[i]==OB_EVENT_CONTROL&&mode[ob_event_mode[i]]==0)||ob_event_sign(b)!=ob_event_side(i,mode));}', ...
      'static void ob_event_remember(ob_model *m,double time,const ob_event_snapshot *snapshot,const int *mode,int preserve){', ...
      '  if(!preserve||!m->event_memory_valid||m->event_memory_time!=time)memset(m->event_reported,0,sizeof(m->event_reported));', ...
      '  m->event_memory_valid=1;m->event_memory_time=time;m->event_snapshot=*snapshot;', ...
      '  memcpy(m->event_mode,mode,sizeof(m->event_mode));}', ...
      'static void ob_event_record(ob_model *m,size_t index,double time){', ...
      '  if(!m->event_memory_valid||m->event_memory_time!=time){memset(m->event_reported,0,sizeof(m->event_reported));m->event_memory_time=time;m->event_memory_valid=1;}', ...
      '  if(!m->event_reported[index]){m->event_count++;m->last_event_time=time;m->event_reported[index]=1;}}');
  emit_process();
  emit_integrate();
  emit_api();

  function add(varargin),lines=[lines varargin];endfunction

  function emit_process()
    if(clocks>0)
      shortest=min(arrayfun(@(c)c.rate(1),root.clock_inventory));
      add('static int ob_clock_close(double a,double b,double origin){', ...
          sprintf('  return isfinite(a)&&isfinite(b)&&fabs(a-b)<=fmin(%s,8.0*DBL_EPSILON*fmax(DBL_MIN,fmax(fabs(origin),fmax(fabs(a),fabs(b)))));}',num(shortest/16)), ...
          'static double ob_clock_time(const ob_model *m,size_t clock){return m->start_time+ob_clock_offset[clock]+m->clock_tick[clock]*ob_clock_period[clock];}');
    endif
    add('static int ob_event_reconcile(ob_model *m,double time,const int *mode){', ...
        '  const ob_clock_frame frame={m->start_time,ob_event_no_due,ob_event_no_tick,mode,1,1};', ...
        '  int status=ob_eval(m,time,m->state,m->value,0,NULL,NULL,m,0.0,OB_INTERVAL_ELAPSED,&frame);', ...
        '  if(status==OB_OK){ob_event_snapshot checked;status=ob_event_collect(m,&checked);}', ...
        '  if(status==OB_OK){m->time=time;}return status;}', ...
        'static int ob_process_hits(ob_model *m,double time,int output,int commit){', ...
        '  unsigned char due[OB_CLOCK_STORAGE]={0};', ...
        sprintf('  unsigned char hit[%d]={0};(void)output;(void)commit;',max(1,root.n)));
    if(clocks>0)
      add('  for(size_t i=0;i<OB_CLOCK_COUNT;++i)due[i]=!(time==m->start_time&&ob_clock_offset[i]>0.0)&&ob_clock_close(ob_clock_time(m,i),time,m->start_time);');
    endif
    add('  const ob_clock_frame event={m->start_time,due,m->clock_tick,NULL,1,0};const ob_clock_frame *frame=&event;(void)frame;');
    for id=delayed
      if(root.clock_ids(id)>0),condition=sprintf('due[%d]',root.clock_ids(id)-1);else condition='commit';endif
      add(sprintf('  if((%s)&&m->pending_valid[%d]){memcpy(m->state+%d,m->pending+%d,%d*sizeof(double));m->pending_valid[%d]=0;}',condition,id-1,root.state_offsets(id),root.state_offsets(id),root.sizes(id),id-1));
    endfor
    for id=reshape(find(strcmp(root.types,'Rate Transition')|strcmp(root.types,'Conditional Subsystem')),1,[])
      if(root.clock_ids(id)>0),condition=sprintf('due[%d]',root.clock_ids(id)-1);else condition='output';endif
      add(sprintf('  hit[%d]=%s;',id-1,condition));
    endfor
    add('  int status=ob_eval(m,time,m->state,m->value,0,NULL,hit,m,0.0,OB_INTERVAL_ELAPSED,frame);if(status!=OB_OK)return status;', ...
        '  ob_event_snapshot checked;status=ob_event_collect(m,&checked);if(status!=OB_OK)return status;');
    for id=delayed(root.clock_ids(delayed)>0)
      source=root.sources{id};o=root.state_offsets(id);n=root.sizes(id);
      add(sprintf('  if(due[%d]){',root.clock_ids(id)-1));
      if(strcmp(root.types{id},'Unit Delay')),add(sprintf('    memcpy(m->pending+%d,m->value+%d,%d*sizeof(double));',o,root.offsets(source),n));
      else add(sprintf('    for(size_t i=0;i<%d;++i)m->pending[%d+i]=m->state[%d+i]+%s*m->value[%d+i];',n,o,o,num(root.flat.sample_times(id,1)),root.offsets(source)));endif
      add(sprintf('    for(size_t i=0;i<%d;++i)if(!isfinite(m->pending[%d+i]))return OB_NONFINITE;',n,o),sprintf('    m->pending_valid[%d]=1;}',id-1));
    endfor
    if(clocks>0)
      add('  for(size_t i=0;i<OB_CLOCK_COUNT;++i)if(due[i]){', ...
          '    double previous=ob_clock_time(m,i);if(m->clock_tick[i]>=9007199254740991.0)return OB_BAD_ARGUMENT;', ...
          '    m->clock_tick[i]+=1.0;double next=ob_clock_time(m,i);', ...
          '    if(!isfinite(next)||next<=previous||next<=time)return OB_BAD_ARGUMENT;}');
    endif
    for id=reshape(find(root.clock_ids>0),1,[]),add(sprintf('  m->tick[%d]=m->clock_tick[%d];',id-1,root.clock_ids(id)-1));endfor
    add('  m->time=time;return OB_OK;}');
  endfunction

  function emit_integrate()
    add('static int ob_integrate_events(ob_model *m,double endpoint,size_t *instants){', ...
        '  while(m->time<endpoint){', ...
        '    const double begin=m->time;double finish=endpoint;');
    if(isfinite(root.event_options.maxstep)),add(sprintf('    finish=fmin(endpoint,begin+fmin(%s,endpoint-begin));',num(root.event_options.maxstep)));endif
    add('    const double slack=fmin((finish-begin)/16.0,8.0*DBL_EPSILON*fmax(DBL_MIN,fmax(fabs(begin),fabs(endpoint))));', ...
        '    if(endpoint-finish<=slack)finish=endpoint;', ...
        '    if(!isfinite(finish)||finish<=begin)return OB_EVENT_ERROR;', ...
        '    ob_event_snapshot at;int mode[OB_EVENT_STORAGE];', ...
        '    int status=ob_event_settle(m,begin,finish,mode,&at);if(status!=OB_OK)return status;', ...
        '    int changed=0;');
    for index=1:numel(guards)
      g=guards(index);
      if(!strcmp(g.side,'control')),continue;endif
      [access,active]=guard_access(root,g.compiled_path);child=sprintf('%schild_%d.',access,g.block_id);
      add(sprintf('    if((%s)&&at.active[%d]&&ob_event_sign(at.value[%d])!=m->%scontrol_sign){ob_event_record(m,%d,begin);changed=1;}',active,index-1,index-1,child,index-1));
    endfor
    if(!isempty(guards))
      add('    if(m->event_memory_valid&&m->event_memory_time==begin){', ...
          '      for(size_t i=0;i<OB_EVENT_COUNT;++i)if(at.active[i]&&m->event_snapshot.active[i]&&at.value[i]==0.0&&m->event_snapshot.value[i]==0.0&&!m->event_reported[i]&&ob_event_kind[i]!=OB_EVENT_CONTROL&&ob_event_side(i,m->event_mode)!=ob_event_side(i,mode)){ob_event_record(m,i,begin);}', ...
          '    }');
    endif
    add('    if(changed){', ...
        '      if(++*instants>1000)return OB_EVENT_ERROR;', ...
        '      ob_event_remember(m,begin,&at,mode,1);return ob_event_reconcile(m,begin,mode);', ...
        '    }', ...
        '    ob_model origin=*m,candidate;ob_event_snapshot sampled;', ...
        '    status=ob_event_flow(&origin,begin,finish,1,mode,&candidate);if(status!=OB_OK)return status;', ...
        '    status=ob_event_collect(&candidate,&sampled);if(status!=OB_OK)return status;', ...
        '    if(!ob_event_same_layout(&at,&sampled))return OB_EVENT_ERROR;', ...
        '    if(!ob_event_crossed(&at,&sampled,mode)){', ...
        '      *m=candidate;ob_event_remember(m,finish,&sampled,mode,0);continue;', ...
        '    }', ...
        '    double lower=begin,upper=finish;const double tolerance=1e-11*(finish-begin);', ...
        '    for(size_t iteration=0;iteration<64;++iteration){', ...
        '      if(upper-lower<=tolerance)break;', ...
        '      const double middle=lower+(upper-lower)/2.0;if(middle<=lower||middle>=upper)break;', ...
        '      ob_model trial;ob_event_snapshot snapshot;', ...
        '      status=ob_event_flow(&origin,begin,middle,0,mode,&trial);if(status!=OB_OK)return status;', ...
        '      status=ob_event_collect(&trial,&snapshot);if(status!=OB_OK)return status;', ...
        '      if(!ob_event_same_layout(&at,&snapshot))return OB_EVENT_ERROR;', ...
        '      if(ob_event_crossed(&at,&snapshot,mode)){upper=middle;candidate=trial;sampled=snapshot;}else lower=middle;', ...
        '    }', ...
        '    if(upper<=begin)return OB_EVENT_ERROR;');
    if(clocks>0)
      add('    if(endpoint-upper<=tolerance){int clock_endpoint=0;', ...
          '      for(size_t i=0;i<OB_CLOCK_COUNT;++i)if(ob_clock_close(ob_clock_time(&origin,i),endpoint,origin.start_time))clock_endpoint=1;', ...
          '      if(clock_endpoint){upper=endpoint;status=ob_event_flow(&origin,begin,upper,1,mode,&candidate);if(status!=OB_OK)return status;', ...
          '        status=ob_event_collect(&candidate,&sampled);if(status!=OB_OK)return status;}', ...
          '      if(!ob_event_same_layout(&at,&sampled))return OB_EVENT_ERROR;', ...
          '    }');
    endif
    add('    *m=candidate;ob_event_remember(m,upper,&sampled,mode,0);');
    if(!isempty(guards)),add('    for(size_t i=0;i<OB_EVENT_COUNT;++i)if(ob_event_one_crossed(i,&at,&sampled,mode))ob_event_record(m,i,upper);');
    else add('    (void)ob_event_one_crossed;(void)ob_event_record;');endif
    add('    if(++*instants>1000)return OB_EVENT_ERROR;', ...
        '    return ob_event_reconcile(m,upper,NULL);', ...
        '  }return OB_OK;}');
  endfunction

  function emit_api()
    add('int ob_model_outputs(ob_model *m){', ...
        '  if(!m||!m->initialized||!isfinite(m->time))return OB_BAD_ARGUMENT;', ...
        '  ob_model work=*m;ob_event_snapshot snapshot;int status=ob_event_snapshot_at(&work,work.time,0,NULL,&snapshot);', ...
        '  if(status==OB_OK){memcpy(m->value,work.value,OB_VALUE_COUNT*sizeof(double));}return status;}', ...
        'int ob_model_set_input_provider(ob_model *m,ob_input_provider provider,ob_input_event event,void *user){', ...
        '  if(!m||!m->initialized||(!provider&&(event||user))||(OB_INPUT_PORT_COUNT==0&&provider))return OB_BAD_ARGUMENT;', ...
        '  ob_model work=*m;work.input_provider=provider;work.input_event=event;work.input_user=user;', ...
        '  int status=ob_event_reconcile(&work,work.time,NULL);ob_event_snapshot snapshot;', ...
        '  if(status==OB_OK){status=ob_event_collect(&work,&snapshot);}', ...
        '  if(status==OB_OK){work.event_memory_valid=0;*m=work;}return status;}', ...
        'int ob_model_init_inputs(ob_model *model,double time,ob_input_provider provider,ob_input_event event,void *user){', ...
        '  if(!model||!isfinite(time)||(!provider&&(event||user))||(OB_INPUT_PORT_COUNT==0&&provider))return OB_BAD_ARGUMENT;', ...
        '  ob_model work;memset(&work,0,sizeof(work));ob_model *m=&work;', ...
        '  m->input_provider=provider;m->input_event=event;m->input_user=user;', ...
        '  m->time=time;m->start_time=time;m->initialized=1;');
    for id=reshape(find(root.numeric_state),1,[]),add(sprintf('  memcpy(m->state+%d,%sp%d,%d*sizeof(double));',root.state_offsets(id),root.prefix,id,root.sizes(id)));endfor
    for id=1:root.n
      if(!isempty(root.children{id})),add(sprintf('  %sgate_reset(&m->child_%d,time);',root.children{id}.prefix,id));endif
    endfor
    if(clocks>0)
      add('  for(size_t i=0;i<OB_CLOCK_COUNT;++i){double first=ob_clock_time(m,i);', ...
          '    if(!isfinite(time+ob_clock_period[i])||time+ob_clock_period[i]<=time||!isfinite(first)||first<time||(ob_clock_offset[i]>0.0&&first<=time))return OB_BAD_ARGUMENT;}');
    endif
    add('  int status=ob_process_hits(m,time,1,0);ob_event_snapshot snapshot;', ...
        '  if(status==OB_OK){status=ob_event_collect(m,&snapshot);}', ...
        '  if(status==OB_OK){*model=work;}return status;}', ...
        'int ob_model_init(ob_model *m,double time){return ob_model_init_inputs(m,time,NULL,NULL,NULL);}', ...
        'int ob_model_step(ob_model *model,double next_time){', ...
        '  if(!model||!model->initialized||!isfinite(next_time)||next_time<=model->time)return OB_BAD_ARGUMENT;', ...
        '  double dt=next_time-model->time;if(!isfinite(dt))return OB_BAD_ARGUMENT;(void)dt;', ...
        '  ob_model work=*model;int status=ob_model_outputs(&work);if(status!=OB_OK)return status;');
    for id=inherited
      source=root.sources{id};o=root.state_offsets(id);n=root.sizes(id);
      if(strcmp(root.types{id},'Unit Delay')),add(sprintf('  memcpy(work.pending+%d,work.value+%d,%d*sizeof(double));',o,root.offsets(source),n));
      else add(sprintf('  for(size_t i=0;i<%d;++i)work.pending[%d+i]=work.state[%d+i]+dt*work.value[%d+i];',n,o,o,root.offsets(source)));endif
      add(sprintf('  work.pending_valid[%d]=1;',id-1),sprintf('  for(size_t i=0;i<%d;++i)if(!isfinite(work.pending[%d+i]))return OB_NONFINITE;',n,o));
    endfor
    add('  size_t instants=0;', ...
        '  while(work.time<next_time){const double start=work.time;double end=next_time;');
    if(clocks>0)
      add('    for(size_t i=0;i<OB_CLOCK_COUNT;++i){double tick=ob_clock_time(&work,i);', ...
          '      if(!isfinite(tick)||tick<=start)return OB_BAD_ARGUMENT;', ...
          '      if(tick<end&&!ob_clock_close(tick,next_time,work.start_time))end=tick;}');
    endif
    add('    const double scheduled_end=end;');
    emit_boundaries(root,'work.','1');
    if(root.input_count>0),add('    status=ob_next_input_boundary(&work,start,&end);if(status!=OB_OK)return status;');endif
    add('    if(!isfinite(end)||end<=start)return OB_BAD_ARGUMENT;', ...
        '    status=ob_integrate_events(&work,end,&instants);if(status!=OB_OK)return status;', ...
        '    if(work.time<end)continue;', ...
        '    if(end==scheduled_end){const int output=end==next_time;status=ob_process_hits(&work,end,output,output);}', ...
        '    else status=ob_event_reconcile(&work,end,NULL);', ...
        '    if(status!=OB_OK)return status;', ...
        '  }*model=work;return OB_OK;}');
  endfunction

  function emit_boundaries(u,access,active)
    for id=reshape(find(strcmp(u.types,'Step')),1,[])
      time=num(u.flat.blocks(id).value(1));add(sprintf('    if((%s)&&%s>start&&%s<end)end=%s;',active,time,time,time));
    endfor
    for id=1:u.n
      child=u.children{id};
      if(!isempty(child)&&strcmp(child.options.mode,'enabled'))
        next=sprintf('%schild_%d.',access,id);
        emit_boundaries(child,next,sprintf('(%s)&&%sinitialized&&%swas_enabled',active,next,next));
      endif
    endfor
  endfunction
endfunction

function [access,active]=guard_access(unit,path)
  access='';active='1';
  for id=path(1:end-1)
    unit=unit.children{id};
    if(!strcmp(unit.options.mode,'enabled')),active='0';endif
    access=sprintf('%schild_%d.',access,id);
    active=sprintf('(%s)&&m->%sinitialized&&m->%swas_enabled',active,access,access);
  endfor
endfunction

function u=unit_at(u,path)
  for id=path,u=u.children{id};endfor
endfunction

function entries=continuous_entries(u,access,guard)
  entries=struct('access',{},'guard',{},'state',{},'source',{},'size',{});
  for id=reshape(find(strcmp(u.types,'Integrator')),1,[])
    source=u.sources{id};
    entries(end+1)=struct('access',access,'guard',guard,'state',u.state_offsets(id),'source',u.offsets(source),'size',u.sizes(id));
  endfor
  for id=1:u.n
    child=u.children{id};
    if(!isempty(child)&&strcmp(child.options.mode,'enabled'))
      next=sprintf('%schild_%d.',access,id);
      active=sprintf('(%s)&&m->%sinitialized&&m->%swas_enabled',guard,next,next);
      nested=continuous_entries(child,next,active);
      if(!isempty(nested)),entries=[entries nested];endif
    endif
  endfor
endfunction

function text=num(value)
  text=sprintf('%.17g',value);
  if(isempty(strfind(text,'.'))&&isempty(strfind(lower(text),'e'))),text=[text '.0'];endif
endfunction
