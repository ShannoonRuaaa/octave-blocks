                                 'Sum','Gain','Constant','Sum'}, ...
      'value',{1,-.2,[],[],child,[],[],-1,.7,[]}, ...
      'name',{'Derivative','Negative start','Time','Gate window','Continuous enable','Output', ...
              'After start','Negative time','Stop','Before stop'}, ...
