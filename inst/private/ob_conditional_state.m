function state = ob_conditional_state (model, start_time, options = [])
  if (isempty(options)), options = ob_execution_options (model); endif
  % trigger_seen marks the first trigger evaluation of a combined context, or
  % of a trigger-only context with initial_control 'compatibility'; it
  % records the sample without an edge (see ob_conditional_eval).
  initial = 0;
  if (! ischar (options.initial_control)), initial = sign (options.initial_control); endif
  % initial_outputs holds each port's initial output once a scalar one has
  % been broadcast to the port's shape (output_shaped marks ports whose
  % shape is known; shapes_probed records that ob_conditional_output_shapes
  % has looked for them).  reset_due and gating serve enabled bodies with
  % inner clocks (ob_conditional_buffers, ob_refresh_conditional_outputs,
  % ob_conditional_disabled_reset).
  count = numel (options.initial_outputs);
  state = struct ('initialized', false, 'child', [], 'outputs', {options.initial_outputs}, ...
                  'was_enabled', false, 'enable_sign', 0, 'reset_pending', false, ...
                  'previous_sign', initial, ...
                  'last_rising', false, 'last_falling', false, 'last_executed', false, ...
                  'last_sample', start_time, 'advance_interval', 0, 'executions', [], ...
                  'control_sign', initial, ...
                  'continuous_elapsed', 0, 'continuous_active_since', [], ...
                  'trigger_seen', false, ...
                  'initial_outputs', {options.initial_outputs}, ...
                  'output_shaped', ! cellfun (@isscalar, options.initial_outputs), ...
                  'reset_due', false (1, count), ...
                  'gating', [], 'shapes_probed', all (! cellfun (@isscalar, options.initial_outputs)));
endfunction
