function lines = ob_c_delay_lines (part, d)
  % C99 Transport Delay support for the flat ob_codegen exporter.
  %
  % The generated history reproduces private/ob_transport_delay.m and the
  % segment loop of private/ob_runtime_integrate.m operation by operation,
  % so compiled results equal ob_run bit for bit on the same platform:
  % left/right samples at discontinuities, the stored start time, merging of
  % samples a few ulps apart, cubic Hermite interpolation with one-sided
  % slopes inside continuous pieces, pruning, delayed jumps and start + T as
  % solver boundaries, and segments no longer than the shortest delay.
  % Each history is a bounded ring buffer (ob_c_delay_capacity); appending
  % to a full one returns OB_DELAY_OVERFLOW and leaves the caller's context
  % unchanged.
  %
  % Histories are never copied for rollback.  ob_model_step works in place
  % on the context: it saves the context without its history storage (the
  % "core", which includes each history's head/count/start) and the last two
  % samples of each history, the only stored samples a step can change in
  % place.  Appends never reuse a slot that was live when the step began, and
  % unused slots are kept zero, so a failed step is undone exactly (byte for
  % byte) by restoring the core and those two samples and clearing what was
  % appended; a successful step clears the slots it pruned.  Stack use and
  % per-step cost therefore do not grow with the history capacity.
  %
  % part 'declarations': counts and storage sizes needed by ob_model
  % part 'fields':       ob_model members; they must be the last members,
  %                      because the core is everything before delay_t
  % part 'support':      tables, history operations, rollback helpers and
  %                      ob_delay_record_all (before ob_eval, which reads
  %                      delay outputs)
  % part 'interval':     boundaries and segments of one scheduled interval
  %                      (after ob_integrate)
  % d is a struct from ob_codegen with fields ids, delay, width, input_width,
  % source_offset, capacity, initial (cell of column values), steps (Step
  % times), inputs (root input signals), continuous and count_steps.
  lines = {};
  count = numel (d.ids);
  sample_offsets = cumsum ([0 d.capacity(1:end-1)]);
  value_offsets = cumsum ([0 d.capacity(1:end-1) .* d.width(1:end-1)]);
  initial_offsets = cumsum ([0 d.width(1:end-1)]);
  switch (part)
    case 'declarations'
      % OB_DELAY_SEGMENTS: a gap needs more than 1e6 segments of at most the
      % shortest delay, where ob_run raises an error.
      add (sprintf ('enum { OB_DELAY_COUNT = %d, OB_DELAY_OVERFLOW = 5, OB_DELAY_SEGMENTS = 6 };', count), ...
           sprintf ('#define OB_DELAY_SAMPLE_STORAGE %d', sum (d.capacity)), ...
           sprintf ('#define OB_DELAY_VALUE_STORAGE %d', sum (d.capacity .* d.width)), ...
           sprintf ('#define OB_DELAY_ROW_STORAGE %d', max (d.width)), ...
           sprintf ('#define OB_DELAY_JUMP_STORAGE %d', sum (floor (d.capacity / 2) + 1)));
    case 'fields'
      % delay_base is the head when the current step began (equal to the
      % head between calls).  delay_jump is scratch for one interval's
      % delayed jumps, zero between calls.
      add ('  size_t delay_head[OB_DELAY_COUNT];', ...
           '  size_t delay_count[OB_DELAY_COUNT];', ...
           '  size_t delay_base[OB_DELAY_COUNT];', ...
           '  double delay_start[OB_DELAY_COUNT];', ...
           '  double delay_t[OB_DELAY_SAMPLE_STORAGE];', ...
           '  double delay_u[OB_DELAY_VALUE_STORAGE];', ...
           '  double delay_jump[OB_DELAY_JUMP_STORAGE];', ...
           '  unsigned char delay_left[OB_DELAY_SAMPLE_STORAGE];');
    case 'support'
      support ();
    case 'interval'
      interval ();
    otherwise
      error ('ob_c_delay_lines: unknown part');
  endswitch

  function support ()
    add ('/* Transport Delay histories (private/ob_transport_delay.m). */', ...
         ['const double ob_delay_time[OB_DELAY_COUNT] = {' numbers(d.delay) '};'], ...
         ['const size_t ob_delay_capacity[OB_DELAY_COUNT] = {' integers(d.capacity) '};'], ...
         ['static const size_t ob_delay_sample_offset[OB_DELAY_COUNT] = {' integers(sample_offsets) '};'], ...
         ['static const size_t ob_delay_value_offset[OB_DELAY_COUNT] = {' integers(value_offsets) '};'], ...
         ['static const size_t ob_delay_width[OB_DELAY_COUNT] = {' integers(d.width) '};'], ...
         ['static const size_t ob_delay_initial_offset[OB_DELAY_COUNT] = {' integers(initial_offsets) '};'], ...
         ['static const double ob_delay_initial[' sprintf('%d', sum(d.width)) '] = {' numbers(vertcat(d.initial{:})) '};'], ...
         ['static const double ob_delay_shortest = ' numbers(min(d.delay)) ';'], ...
         '/* Octave evaluates scalar x^2 with pow(); a constant exponent would let', ...
         '   the compiler substitute x*x, which can round differently. */', ...
         'static volatile double ob_delay_two = 2.0;', ...
         '/* same_instant(): the engine''s time_equal with the delay as the spacing. */', ...
         'static int ob_delay_same(double a, double b, double delay) {', ...
         '  return fabs(a - b) <= fmin(delay/16.0, 8.0*DBL_EPSILON*fmax(fmax(fabs(a), fabs(b)), DBL_MIN));', ...
         '}', ...
         'static size_t ob_delay_slot(const ob_model *model, size_t d, size_t i) {', ...
         '  size_t slot = model->delay_head[d] + i;', ...
         '  if (slot >= ob_delay_capacity[d]) slot -= ob_delay_capacity[d];', ...
         '  return slot;', ...
         '}', ...
         'static double ob_delay_t(const ob_model *model, size_t d, size_t i) {', ...
         '  return model->delay_t[ob_delay_sample_offset[d] + ob_delay_slot(model, d, i)];', ...
         '}', ...
         'static const double *ob_delay_u(const ob_model *model, size_t d, size_t i) {', ...
         '  return model->delay_u + ob_delay_value_offset[d] + ob_delay_slot(model, d, i)*ob_delay_width[d];', ...
         '}', ...
         '/* Number of samples at or before time: Octave lookup(t, time). */', ...
         'static size_t ob_delay_count_le(const ob_model *model, size_t d, double time) {', ...
         '  size_t low = 0, high = model->delay_count[d];', ...
         '  while (low < high) {', ...
         '    const size_t middle = low + (high - low)/2;', ...
         '    if (ob_delay_t(model, d, middle) <= time) low = middle + 1; else high = middle;', ...
         '  }', ...
         '  return low;', ...
         '}', ...
         '/* Slope at zero-based sample i, element e: the derivative of the quadratic', ...
         '   through i and its neighbours, never across a stored jump. */', ...
         'static double ob_delay_slope(const ob_model *model, size_t d, size_t i, size_t e) {', ...
         '  const size_t n = model->delay_count[d];', ...
         '  const double ti = ob_delay_t(model, d, i), ui = ob_delay_u(model, d, i)[e];', ...
         '  const int left = i > 0 && ob_delay_t(model, d, i-1) < ti;', ...
         '  const int right = i + 1 < n && ob_delay_t(model, d, i+1) > ti;', ...
         '  if (left && right) {', ...
         '    const double h0 = ti - ob_delay_t(model, d, i-1), h1 = ob_delay_t(model, d, i+1) - ti;', ...
         '    const double s0 = (ui - ob_delay_u(model, d, i-1)[e])/h0;', ...
         '    const double s1 = (ob_delay_u(model, d, i+1)[e] - ui)/h1;', ...
         '    return (h1*s0 + h0*s1)/(h0 + h1);', ...
         '  } else if (right) {', ...
         '    const double t1 = ob_delay_t(model, d, i+1), u1 = ob_delay_u(model, d, i+1)[e];', ...
         '    const double h0 = t1 - ti, s0 = (u1 - ui)/h0;', ...
         '    if (i + 2 < n && ob_delay_t(model, d, i+2) > t1) {', ...
         '      const double h1 = ob_delay_t(model, d, i+2) - t1, s1 = (ob_delay_u(model, d, i+2)[e] - u1)/h1;', ...
         '      return s0*(2.0*h0 + h1)/(h0 + h1) - s1*h0/(h0 + h1);', ...
         '    }', ...
         '    return s0;', ...
         '  } else if (left) {', ...
         '    const double t0 = ob_delay_t(model, d, i-1), u0 = ob_delay_u(model, d, i-1)[e];', ...
         '    const double h1 = ti - t0, s1 = (ui - u0)/h1;', ...
         '    if (i >= 2 && ob_delay_t(model, d, i-2) < t0) {', ...
         '      const double h0 = t0 - ob_delay_t(model, d, i-2), s0 = (u0 - ob_delay_u(model, d, i-2)[e])/h0;', ...
         '      return s1*(2.0*h1 + h0)/(h0 + h1) - s0*h1/(h0 + h1);', ...
         '    }', ...
         '    return s1;', ...
         '  }', ...
         '  return 0.0;', ...
         '}', ...
         'static void ob_delay_copy(const ob_model *model, size_t d, size_t i, double *y) {', ...
         '  memcpy(y, ob_delay_u(model, d, i), ob_delay_width[d]*sizeof(double));', ...
         '}', ...
         '/* Delayed output; left selects the left limit at a jump or at start + T. */', ...
         'static void ob_delay_output(const ob_model *model, size_t d, double time, int left, double *y) {', ...
         '  const size_t n = model->delay_count[d], w = ob_delay_width[d];', ...
         '  const double delay = ob_delay_time[d];', ...
         '  if (n == 0) { memcpy(y, ob_delay_initial + ob_delay_initial_offset[d], w*sizeof(double)); return; }', ...
         '  const double start = model->delay_start[d], boundary = start + delay;', ...
         '  const int at_start = ob_delay_same(time, boundary, delay);', ...
         '  if ((time < boundary && !at_start) || (left && at_start)) {', ...
         '    memcpy(y, ob_delay_initial + ob_delay_initial_offset[d], w*sizeof(double));', ...
         '    return;', ...
         '  }', ...
         '  double tau = time - delay;', ...
         '  if (!(tau >= start)) tau = start;', ...
         '  if (at_start) tau = start;', ...
         '  size_t k = ob_delay_count_le(model, d, tau);', ...
         '  /* A query at a sample''s shifted time reads that sample exactly. */', ...
         '  if (k < n && ob_delay_same(ob_delay_t(model, d, k) + delay, time, delay)) {', ...
         '    tau = ob_delay_t(model, d, k); k += 1;', ...
         '    while (k < n && ob_delay_t(model, d, k) == tau) k += 1;', ...
         '  } else if (k > 0 && ob_delay_t(model, d, k-1) != tau', ...
         '             && ob_delay_same(ob_delay_t(model, d, k-1) + delay, time, delay)) {', ...
         '    tau = ob_delay_t(model, d, k-1);', ...
         '  }', ...
         '  const double last = ob_delay_t(model, d, n-1);', ...
         '  if (tau >= last) {', ...
         '    k = n;', ...
         '    if (left && tau == last && k > 1 && ob_delay_t(model, d, k-2) == last) k -= 1;', ...
         '    ob_delay_copy(model, d, k-1, y);', ...
         '    return;', ...
         '  }', ...
         '  if (k < 1) k = 1;', ...
         '  if (left && ob_delay_t(model, d, k-1) == tau) {', ...
         '    while (k > 1 && ob_delay_t(model, d, k-2) == tau) k -= 1;', ...
         '    ob_delay_copy(model, d, k-1, y);', ...
         '    return;', ...
         '  }', ...
         '  const double a = ob_delay_t(model, d, k-1), b = ob_delay_t(model, d, k);', ...
         '  if (b == a) { ob_delay_copy(model, d, k, y); return; }', ...
         '  const double h = b - a, weight = (tau - a)/h;', ...
         '  const double h00 = (1.0 + 2.0*weight)*pow(1.0 - weight, ob_delay_two);', ...
         '  const double h10 = weight*pow(1.0 - weight, ob_delay_two);', ...
         '  const double h01 = pow(weight, ob_delay_two)*(3.0 - 2.0*weight);', ...
         '  const double h11 = pow(weight, ob_delay_two)*(weight - 1.0);', ...
         '  const double *ua = ob_delay_u(model, d, k-1), *ub = ob_delay_u(model, d, k);', ...
         '  for (size_t e = 0; e < w; ++e) {', ...
         '    const double da = ob_delay_slope(model, d, k-1, e), db = ob_delay_slope(model, d, k, e);', ...
         '    y[e] = h00*ua[e] + h10*h*da + h01*ub[e] + h11*h*db;', ...
         '  }', ...
         '}', ...
         '/* Zero one physical slot: unused slots are kept zero (see ob_delay_finish). */', ...
         'static void ob_delay_clear(ob_model *model, size_t d, size_t slot) {', ...
         '  model->delay_t[ob_delay_sample_offset[d] + slot] = 0.0;', ...
         '  memset(model->delay_u + ob_delay_value_offset[d] + slot*ob_delay_width[d], 0, ob_delay_width[d]*sizeof(double));', ...
         '  model->delay_left[ob_delay_sample_offset[d] + slot] = 0;', ...
         '}', ...
         'static int ob_delay_append(ob_model *model, size_t d, double time, const double *row, int left) {', ...
         '  const size_t n = model->delay_count[d], capacity = ob_delay_capacity[d];', ...
         '  /* Slots live when the step began are not reused before it commits, so', ...
         '     a failed step is undone without copying the history. */', ...
         '  const size_t pruned = (model->delay_head[d] + capacity - model->delay_base[d]) % capacity;', ...
         '  if (pruned + n >= capacity) return OB_DELAY_OVERFLOW;', ...
         '  const size_t slot = ob_delay_slot(model, d, n);', ...
         '  model->delay_t[ob_delay_sample_offset[d] + slot] = time;', ...
         '  memcpy(model->delay_u + ob_delay_value_offset[d] + slot*ob_delay_width[d], row, ob_delay_width[d]*sizeof(double));', ...
         '  model->delay_left[ob_delay_sample_offset[d] + slot] = (unsigned char)(left != 0);', ...
         '  model->delay_count[d] = n + 1;', ...
         '  return OB_OK;', ...
         '}', ...
         '/* Record an accepted input sample; left marks a left limit. */', ...
         'static int ob_delay_record(ob_model *model, size_t d, double time, const double *input, size_t input_width, int left) {', ...
         '  const size_t w = ob_delay_width[d];', ...
         '  const double delay = ob_delay_time[d];', ...
         '  double row[OB_DELAY_ROW_STORAGE];', ...
         '  /* A scalar input expands to a matrix initial output''s shape. */', ...
         '  for (size_t e = 0; e < w; ++e) row[e] = input[input_width == 1 ? 0 : e];', ...
         '  size_t n = model->delay_count[d];', ...
         '  if (n > 0 && time < ob_delay_t(model, d, n-1)) return OB_BAD_ARGUMENT;', ...
         '  if (n == 0) model->delay_start[d] = time;', ...
         '  /* Prune before changing the tail.  ob_transport_delay prunes afterwards;', ...
         '     the result is the same because the last two samples always survive', ...
         '     and the new sample lies after time - delay, but appending to a', ...
         '     pruned buffer needs one slot less. */', ...
         '  size_t keep = ob_delay_count_le(model, d, time - delay);', ...
         '  if (keep > 0) {', ...
         '    while (keep > 1 && ob_delay_t(model, d, keep-2) == ob_delay_t(model, d, keep-1)) keep -= 1;', ...
         '    keep = keep > 1 ? keep - 1 : 1;', ...
         '    if (keep > 1) {', ...
         '      model->delay_head[d] = ob_delay_slot(model, d, keep-1);', ...
         '      model->delay_count[d] -= keep - 1;', ...
         '    }', ...
         '  }', ...
         '  n = model->delay_count[d];', ...
         '  if (n == 0) return ob_delay_append(model, d, time, row, left);', ...
         '  const double last = ob_delay_t(model, d, n-1);', ...
         '  const size_t slot = ob_delay_slot(model, d, n-1);', ...
         '  double *last_u = model->delay_u + ob_delay_value_offset[d] + slot*w;', ...
         '  unsigned char *last_left = model->delay_left + ob_delay_sample_offset[d] + slot;', ...
         '  int same_row = 1;', ...
         '  for (size_t e = 0; e < w; ++e) if (last_u[e] != row[e]) same_row = 0;', ...
         '  if (time > last && ob_delay_same(time, last, delay)) {', ...
         '    /* One instant a few ulps apart: the later sample is the right limit. */', ...
         '    if (!same_row) {', ...
         '      if (n > 1 && ob_delay_t(model, d, n-2) == last) memcpy(last_u, row, w*sizeof(double));', ...
         '      else { *last_left = 1; return ob_delay_append(model, d, last, row, 0); }', ...
         '    }', ...
         '  } else if (time == last) {', ...
         '    if (!left && *last_left && !same_row) return ob_delay_append(model, d, time, row, 0);', ...
         '    if (n > 1 && ob_delay_t(model, d, n-2) == time && left) {', ...
         '      /* A repeated left sample replaces the stored jump. */', ...
         '      ob_delay_clear(model, d, slot);', ...
         '      model->delay_count[d] = n - 1;', ...
         '      const size_t previous = ob_delay_slot(model, d, n-2);', ...
         '      last_u = model->delay_u + ob_delay_value_offset[d] + previous*w;', ...
         '      last_left = model->delay_left + ob_delay_sample_offset[d] + previous;', ...
         '    }', ...
         '    memcpy(last_u, row, w*sizeof(double));', ...
         '    *last_left = (unsigned char)(left != 0);', ...
         '  } else {', ...
         '    return ob_delay_append(model, d, time, row, left);', ...
         '  }', ...
         '  return OB_OK;', ...
         '}', ...
         'static int ob_delay_record_all(ob_model *model, double time, const double *v, int left) {', ...
         '  int status;');
    for k = 1:count
      add (sprintf ('  status = ob_delay_record(model, %d, time, v + %d, %d, left);', ...
                    k-1, d.source_offset(k), d.input_width(k)), ...
           '  if (status != OB_OK) return status;');
    endfor
    add ('  (void)status;', '  return OB_OK;', '}');
    rollback ();
  endfunction

  function rollback ()
    % In-place rollback of init and step (see the header comment).  Within
    % one step, a removal lowers a history's tail by one slot at most once
    % between appends, so the step changes in place only the last two samples
    % that were live when it began, and it writes no slot more than one past
    % the current tail.
    add ('/* Rollback state: the context without its history storage, and the', ...
         '   last two samples of each history. */', ...
         '#define OB_DELAY_CORE_BYTES offsetof(ob_model, delay_t)', ...
         'typedef struct {', ...
         '  unsigned char core[OB_DELAY_CORE_BYTES];', ...
         '  double t[OB_DELAY_COUNT][2];', ...
         '  double u[OB_DELAY_COUNT][2][OB_DELAY_ROW_STORAGE];', ...
         '  unsigned char left[OB_DELAY_COUNT][2];', ...
         '} ob_delay_undo;', ...
         'static void ob_delay_save_slot(const ob_model *model, size_t d, size_t slot, ob_delay_undo *undo, size_t j) {', ...
         '  undo->t[d][j] = model->delay_t[ob_delay_sample_offset[d] + slot];', ...
         '  memcpy(undo->u[d][j], model->delay_u + ob_delay_value_offset[d] + slot*ob_delay_width[d], ob_delay_width[d]*sizeof(double));', ...
         '  undo->left[d][j] = model->delay_left[ob_delay_sample_offset[d] + slot];', ...
         '}', ...
         'static void ob_delay_load_slot(ob_model *model, size_t d, size_t slot, const ob_delay_undo *undo, size_t j) {', ...
         '  model->delay_t[ob_delay_sample_offset[d] + slot] = undo->t[d][j];', ...
         '  memcpy(model->delay_u + ob_delay_value_offset[d] + slot*ob_delay_width[d], undo->u[d][j], ob_delay_width[d]*sizeof(double));', ...
         '  model->delay_left[ob_delay_sample_offset[d] + slot] = undo->left[d][j];', ...
         '}', ...
         '/* Before a step: between calls delay_base equals delay_head. */', ...
         'static void ob_delay_begin(const ob_model *model, ob_delay_undo *undo) {', ...
         '  memcpy(undo->core, model, sizeof(undo->core));', ...
         '  for (size_t d = 0; d < OB_DELAY_COUNT; ++d) {', ...
         '    const size_t n = model->delay_count[d];', ...
         '    for (size_t j = 0; j < 2 && j < n; ++j) ob_delay_save_slot(model, d, ob_delay_slot(model, d, n-1-j), undo, j);', ...
         '  }', ...
         '}', ...
         '/* After a step: commit (clear the slots pruned by the step) or undo it. */', ...
         'static void ob_delay_finish(ob_model *model, const ob_delay_undo *undo, int status) {', ...
         '  size_t reach[OB_DELAY_COUNT];', ...
         '  for (size_t d = 0; d < OB_DELAY_COUNT; ++d) {', ...
         '    const size_t capacity = ob_delay_capacity[d];', ...
         '    const size_t pruned = (model->delay_head[d] + capacity - model->delay_base[d]) % capacity;', ...
         '    if (status == OB_OK) {', ...
         '      for (size_t i = 0; i < pruned; ++i) ob_delay_clear(model, d, (model->delay_base[d] + i) % capacity);', ...
         '      model->delay_base[d] = model->delay_head[d];', ...
         '    }', ...
         '    reach[d] = pruned + model->delay_count[d] + 1;', ...
         '  }', ...
         '  if (status == OB_OK) return;', ...
         '  memcpy(model, undo->core, sizeof(undo->core));', ...
         '  for (size_t d = 0; d < OB_DELAY_COUNT; ++d) {', ...
         '    const size_t capacity = ob_delay_capacity[d], n = model->delay_count[d];', ...
         '    for (size_t i = n; i < reach[d] && i < capacity; ++i) ob_delay_clear(model, d, ob_delay_slot(model, d, i));', ...
         '    for (size_t j = 0; j < 2 && j < n; ++j) ob_delay_load_slot(model, d, ob_delay_slot(model, d, n-1-j), undo, j);', ...
         '  }', ...
         '}', ...
         '/* Initialization resets every history and records into physical slot 0. */', ...
         'static void ob_delay_begin_init(const ob_model *model, ob_delay_undo *undo) {', ...
         '  memcpy(undo->core, model, sizeof(undo->core));', ...
         '  for (size_t d = 0; d < OB_DELAY_COUNT; ++d) ob_delay_save_slot(model, d, 0, undo, 0);', ...
         '}', ...
         'static void ob_delay_finish_init(ob_model *model, const ob_delay_undo *undo, int status) {', ...
         '  for (size_t d = 0; d < OB_DELAY_COUNT; ++d) {', ...
         '    if (status != OB_OK) { ob_delay_load_slot(model, d, 0, undo, 0); continue; }', ...
         '    /* A context may hold anything before its first initialization. */', ...
         '    for (size_t i = model->delay_count[d]; i < ob_delay_capacity[d]; ++i) ob_delay_clear(model, d, ob_delay_slot(model, d, i));', ...
         '  }', ...
         '  if (status != OB_OK) memcpy(model, undo->core, sizeof(undo->core));', ...
         '  else memset(model->delay_jump, 0, sizeof(model->delay_jump));', ...
         '}');
  endfunction

  function interval ()
    add ('/* Is time the same instant as an existing boundary of [start, finish]:', ...
         '   an endpoint, a Step time, an input knot inside, or a kept jump? */', ...
         'static int ob_delay_near(const ob_model *model, double start, double finish, double time,', ...
         '                         double delay, const double *jumps, size_t jump_count, int *near_boundary) {', ...
         '  (void)model;', ...
         '  *near_boundary = 1;', ...
         '  if (ob_delay_same(start, time, delay) || ob_delay_same(finish, time, delay)) return OB_OK;');
    for s = d.steps
      add (sprintf ('  if (%s > start && %s < finish && ob_delay_same(%s, time, delay)) return OB_OK;', ...
                    numbers(s), numbers(s), numbers(s)));
    endfor
    if (! isempty (d.inputs))
      % same_instant never exceeds delay/16, so scanning knots within
      % delay/8 of time finds every candidate.
      add ('  if (model->input_provider) {', ...
           '    if (model->input_event) {', ...
           '      double after = time - delay/8.0;', ...
           '      const double before = time + delay/8.0;', ...
           '      while (after < before) {', ...
           '        const double knot = model->input_event(after, before, model->input_user);', ...
           '        if (!isfinite(knot) || knot <= after || knot > before) return OB_INPUT_ERROR;', ...
           '        if (knot > start && knot < finish && ob_delay_same(knot, time, delay)) return OB_OK;', ...
           '        after = knot;', ...
           '      }', ...
           '    }', ...
           '  } else {');
      for port = 1:numel (d.inputs)
        rows = numel (d.inputs{port}.t);
        add (sprintf ('    for (size_t i = ob_input_upper_bound(ob_input_t%d, %d, time - delay/8.0);', port, rows), ...
             sprintf ('         i < %d && ob_input_t%d[i] <= time + delay/8.0; ++i)', rows, port), ...
             sprintf ('      if (ob_input_t%d[i] > start && ob_input_t%d[i] < finish && ob_delay_same(ob_input_t%d[i], time, delay)) return OB_OK;', port, port, port));
      endfor
      add ('  }');
    endif
    add ('  for (size_t j = 0; j < jump_count; ++j) if (ob_delay_same(jumps[j], time, delay)) return OB_OK;', ...
         '  *near_boundary = 0;', ...
         '  return OB_OK;', ...
         '}', ...
         '/* One segment: right limits at an interior boundary, RK4, left limits at its end. */', ...
         'static int ob_delay_segment(ob_model *work, double begin, double end, int first) {', ...
         '  double initial[OB_VALUE_COUNT], final[OB_VALUE_COUNT];', ...
         '  int status;', ...
         '  if (!first) {', ...
         '    status = ob_eval(work, begin, work->state, initial, 0, NULL, NULL);', ...
         '    if (status != OB_OK) return status;', ...
         '    status = ob_delay_record_all(work, begin, initial, 0);', ...
         '    if (status != OB_OK) return status;', ...
         '  }');
    if (d.continuous)
      add ('  status = ob_integrate(work, begin, end, work->state, first ? NULL : initial);', ...
           '  if (status != OB_OK) return status;');
      if (d.count_steps), add ('  work->integration_steps += 1.0;'); endif
    endif
    add ('  status = ob_eval(work, end, work->state, final, 1, NULL, NULL);', ...
         '  if (status != OB_OK) return status;', ...
         '  return ob_delay_record_all(work, end, final, 1);', ...
         '}', ...
         '/* Integrate one scheduled interval as ob_runtime_integrate does: Step times,', ...
         '   input knots and delayed jumps (from the histories at its start, without', ...
         '   duplicating an existing boundary) split it, and every resulting gap is', ...
         '   divided into equal pieces no longer than the shortest delay.  The jump', ...
         '   list lives in the context (its size follows the histories), and', ...
         '   *used counts the entries written so that they can be cleared. */', ...
         'static int ob_delay_interval_run(ob_model *work, double start, double finish, size_t *used) {', ...
         '  double *const jumps = work->delay_jump;', ...
         '  size_t jump_count = 0;', ...
         '  int status;', ...
         '  for (size_t d = 0; d < OB_DELAY_COUNT; ++d) {', ...
         '    const size_t n = work->delay_count[d];', ...
         '    const double delay = ob_delay_time[d];', ...
         '    for (size_t j = 0; j <= n; ++j) {', ...
         '      double candidate;', ...
         '      if (j + 1 < n) {', ...
         '        if (ob_delay_t(work, d, j) != ob_delay_t(work, d, j+1)) continue;', ...
         '        candidate = ob_delay_t(work, d, j) + delay;', ...
         '      } else if (j == n && n > 0) {', ...
         '        candidate = work->delay_start[d] + delay;', ...
         '      } else {', ...
         '        continue;', ...
         '      }', ...
         '      if (!(candidate > start && candidate < finish)) continue;', ...
         '      int near_boundary;', ...
         '      status = ob_delay_near(work, start, finish, candidate, delay, jumps, jump_count, &near_boundary);', ...
         '      if (status != OB_OK) return status;', ...
         '      if (near_boundary) continue;', ...
         '      if (jump_count >= OB_DELAY_JUMP_STORAGE) return OB_DELAY_OVERFLOW;', ...
         '      jumps[jump_count++] = candidate;', ...
         '      *used = jump_count;', ...
         '    }', ...
         '  }', ...
         '  for (size_t i = 1; i < jump_count; ++i) {', ...
         '    const double value = jumps[i];', ...
         '    size_t j = i;', ...
         '    while (j > 0 && jumps[j-1] > value) { jumps[j] = jumps[j-1]; --j; }', ...
         '    jumps[j] = value;', ...
         '  }', ...
         '  double previous = start;', ...
         '  size_t next_jump = 0;', ...
         '  int first = 1;', ...
         '  while (previous < finish) {', ...
         '    double next = finish;');
    for s = d.steps
      add (sprintf ('    if (%s > previous && %s < next) next = %s;', numbers(s), numbers(s), numbers(s)));
    endfor
    if (! isempty (d.inputs))
      add ('    status = ob_next_input_boundary(work, previous, &next);', ...
           '    if (status != OB_OK) return status;');
    endif
    add ('    while (next_jump < jump_count && jumps[next_jump] <= previous) ++next_jump;', ...
         '    if (next_jump < jump_count && jumps[next_jump] < next) next = jumps[next_jump];', ...
         '    if (!isfinite(next) || next <= previous) return OB_BAD_ARGUMENT;', ...
         '    const double gap = next - previous;', ...
         '    const double pieces = ceil(gap/ob_delay_shortest*(1.0 - 4.0*DBL_EPSILON));', ...
         '    /* ob_run rejects more than 1e6 segments per scheduled interval gap. */', ...
         '    if (!(pieces <= 1e6)) return OB_DELAY_SEGMENTS;', ...
         '    const size_t count = pieces > 1.0 ? (size_t)pieces : 1;', ...
         '    const double piece = gap/(double)count;', ...
         '    for (size_t p = 1; p <= count; ++p) {', ...
         '      const double begin = p == 1 ? previous : previous + (double)(p-1)*piece;', ...
         '      const double end = p == count ? next : previous + (double)p*piece;', ...
         '      status = ob_delay_segment(work, begin, end, first);', ...
         '      if (status != OB_OK) return status;', ...
         '      first = 0;', ...
         '    }', ...
         '    previous = next;', ...
         '  }', ...
         '  return OB_OK;', ...
         '}', ...
         'static int ob_delay_interval(ob_model *work, double start, double finish) {', ...
         '  size_t used = 0;', ...
         '  const int status = ob_delay_interval_run(work, start, finish, &used);', ...
         '  /* Scratch is not context state: keep it zero between calls. */', ...
         '  memset(work->delay_jump, 0, used*sizeof(double));', ...
         '  return status;', ...
         '}');
  endfunction

  function add (varargin)
    lines = [lines varargin];
  endfunction
endfunction

function text = numbers (values)
  text = ob_c_number_list (values);
endfunction

function text = integers (values)
  text = sprintf ('%d,', values); text(end) = [];
endfunction
