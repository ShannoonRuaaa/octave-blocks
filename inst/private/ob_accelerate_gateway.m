function text = ob_accelerate_gateway (external = false, events = false)
  % MEX gateway appended to an ob_codegen export by ob_accelerate.
  %
  % [values, ticks, status, failed, steps, message, call, log] = ob_accel_<key> (t)
  % [...] = ob_accel_<key> (t, helper)      (exports with external Functions)
  %   values  OB_VALUE_COUNT x numel(t) model values after init/each step
  %   ticks   explicit-clock tick counters (blocks with a positive period,
  %           in block order) after init/each step
  %   status  0 or the generated OB_* code (-1: out of memory / no thread)
  %   failed  one-based sample index of a failure (0 on success)
  %   steps   integration steps taken (ob_run integration_steps)
  %   message failure text of an external Function call ('' otherwise)
  %   call    one-based ob_external_name index of that call (0 otherwise)
  %   log     event records (typed exports with zero crossings, events =
  %           true; 0x5 otherwise): one row per counted record with the
  %           one-based guard index, time, direction, kind (1 control
  %           change, 2 plateau departure, 3 crossing) and the number of the
  %           search step that logged it; see ob_accelerate's
  %           instrument_typed
  %   helper  handle to private/ob_accelerate_call, which evaluates a Function
  %           block's Octave function and returns its error message instead
  %           of throwing
  %
  % The simulation runs on a worker thread with a large reserved stack:
  % ob_eval, the integrator stages and the rollback copy of the context (the
  % whole ob_model without delays; only its core with delays, whose
  % histories roll back in place) keep value-sized arrays on the stack,
  % which grow with the model, while Octave's main thread has 2 MB.  The
  % context (mxMalloc) and the outputs are allocated beforehand.
  %
  % With external = true, the export calls ob_external_call for Function
  % blocks without a C mapping, which only Octave's main thread may
  % evaluate.  A model whose estimated stack need (twice the rollback
  % context plus 32 value and state arrays plus 64 KB) is at most 256 KB
  % runs on the main thread itself: a thread handshake per call costs
  % several times more than the call (Mackey-Glass ode45: 1.7 s against
  % 0.15 s).  Larger models keep the worker, which posts each call (index,
  % input and output pointers) and blocks until the main thread has
  % evaluated it.  Calls go straight to the function with mexCallMATLAB
  % under the trap flag; only a failed call is repeated through the helper,
  % whose error message is reported (or whose value is used, if the repeat
  % succeeds).  The result must be a real double matrix of the compiled
  % shape (OB_EXTERNAL_SHAPE otherwise) with finite elements
  % (OB_EXTERNAL_NONFINITE otherwise).  An interrupt (Ctrl-C) inside the function unwinds the main
  % thread out of the MEX file (Octave frees the mxMalloc context); a
  % waiting worker then stays blocked, touching nothing, until Octave exits.
  lines = { ...
    '/* ---- Octave Blocks accelerator MEX gateway ---- */', ...
    '#include "mex.h"', ...
    '#include <stdio.h>', ...
    '#include <stdlib.h>', ...
    '#if defined(_WIN32)', ...
    '#include <windows.h>', ...
    '#elif defined(OB_ACCEL_PTHREAD)', ...
    '#include <pthread.h>', ...
    '#endif', ...
    'typedef struct {', ...
    '  ob_model *model;', ...
    '  const double *times; size_t count;', ...
    '  double *values; double *ticks;', ...
    '  const size_t *clocks; size_t clock_count;', ...
    '  double steps; int status; size_t failed;', ...
    '} ob_accel_job;', ...
    'static void ob_accel_run(ob_accel_job *job) {', ...
    '  ob_model *model = job->model;', ...
    '  job->failed = 0; job->steps = 0.0;', ...
    '  if (!model) { job->status = -1; job->failed = 1; return; }', ...
    '  job->status = ob_model_init(model, job->times[0]);', ...
    '  for (size_t s = 0; s < job->count; ++s) {', ...
    '    if (s) job->status = ob_model_step(model, job->times[s]);', ...
    '    if (job->status != OB_OK) { job->failed = s + 1; break; }', ...
    '    memcpy(job->values + s*OB_VALUE_COUNT, model->value, OB_VALUE_COUNT*sizeof(double));', ...
    '    for (size_t k = 0; k < job->clock_count; ++k)', ...
    '      job->ticks[k + s*job->clock_count] = model->tick[job->clocks[k]];', ...
    '  }', ...
    '  job->steps = model->integration_steps;', ...
    '}', ...
    '#if defined(_WIN32)', ...
    'static DWORD WINAPI ob_accel_thread(LPVOID job) { ob_accel_run((ob_accel_job *)job); return 0; }', ...
    '#elif defined(OB_ACCEL_PTHREAD)', ...
    'static void *ob_accel_thread(void *job) { ob_accel_run((ob_accel_job *)job); return NULL; }', ...
    '#endif', ...
    '#ifdef OB_DELAY_CORE_BYTES', ...
    '#define OB_ACCEL_CONTEXT_BYTES ((size_t)OB_DELAY_CORE_BYTES)', ...
    '#else', ...
    '#define OB_ACCEL_CONTEXT_BYTES sizeof(ob_model)', ...
    '#endif', ...
    'static const size_t ob_accel_stack = ((size_t)64 << 20) + 2*OB_ACCEL_CONTEXT_BYTES;'};
  if (events)
    % Grows on the worker thread (malloc is thread-safe); read afterwards.
    % ob_accel_search numbers the zero-crossing search steps (one call at
    % the start of each, see ob_accelerate's instrument_typed); every record
    % carries the number of the step that logged it.
    lines = [lines { ...
      'typedef struct { double *rows; size_t count, capacity; int failed; double search; } ob_accel_log;', ...
      'static ob_accel_log ob_accel_events;', ...
      'static void ob_accel_search(void) { ob_accel_events.search += 1.0; }', ...
      'static void ob_accel_event(size_t index, double time, int direction, int kind) {', ...
      '  ob_accel_log *log = &ob_accel_events;', ...
      '  if (log->failed) return;', ...
      '  if (log->count == log->capacity) {', ...
      '    const size_t capacity = log->capacity ? 2*log->capacity : 64;', ...
      '    double *rows = (double *)realloc(log->rows, capacity*5*sizeof(double));', ...
      '    if (!rows) { log->failed = 1; return; }', ...
      '    log->rows = rows; log->capacity = capacity;', ...
      '  }', ...
      '  double *row = log->rows + 5*log->count++;', ...
      '  row[0] = (double)index + 1.0; row[1] = time; row[2] = (double)direction; row[3] = (double)kind;', ...
      '  row[4] = log->search;', ...
      '}'}];
  endif
  if (! external)
    lines = [lines { ...
      'static int ob_accel_launch(ob_accel_job *job) {', ...
      '#if defined(_WIN32)', ...
      '  HANDLE thread = CreateThread(NULL, ob_accel_stack, ob_accel_thread, job, STACK_SIZE_PARAM_IS_A_RESERVATION, NULL);', ...
      '  if (!thread) return 0;', ...
      '  WaitForSingleObject(thread, INFINITE);', ...
      '  CloseHandle(thread);', ...
      '  return 1;', ...
      '#elif defined(OB_ACCEL_PTHREAD)', ...
      '  pthread_attr_t attr; pthread_t thread; int ok = 0;', ...
      '  if (pthread_attr_init(&attr)) return 0;', ...
      '  if (!pthread_attr_setstacksize(&attr, ob_accel_stack) && !pthread_create(&thread, &attr, ob_accel_thread, job)) {', ...
      '    pthread_join(thread, NULL); ok = 1;', ...
      '  }', ...
      '  pthread_attr_destroy(&attr);', ...
      '  return ok;', ...
      '#else', ...
      '  ob_accel_run(job); return 1;', ...
      '#endif', ...
      '}'}];
  else
    lines = [lines external_lines()];
  endif
  lines = [lines { ...
    'void mexFunction(int nlhs, mxArray *plhs[], int nrhs, const mxArray *prhs[]) {', ...
    '  const int outputs = nlhs > 1 ? nlhs : 1;', ...
    sprintf('  if (nrhs != %d || !mxIsDouble(prhs[0]) || mxIsComplex(prhs[0]) || mxIsSparse(prhs[0])', 1 + external), ...
    '      || mxGetNumberOfElements(prhs[0]) == 0)', ...
    '    mexErrMsgIdAndTxt("octave_blocks:accelerate", "expected a nonempty real double time vector");', ...
    '  static size_t clocks[OB_BLOCK_COUNT];', ...
    '  size_t clock_count = 0;', ...
    '  for (size_t b = 0; b < OB_BLOCK_COUNT; ++b) if (ob_sample_period[b] > 0.0) clocks[clock_count++] = b;', ...
    '  const size_t count = mxGetNumberOfElements(prhs[0]);', ...
    '  mxArray *results[8];', ...
    '  results[0] = mxCreateDoubleMatrix(OB_VALUE_COUNT, count, mxREAL);', ...
    '  results[1] = mxCreateDoubleMatrix(clock_count, count, mxREAL);', ...
    '  ob_accel_job job;', ...
    '  job.model = (ob_model *)mxMalloc(sizeof(ob_model));', ...
    '  job.times = mxGetPr(prhs[0]); job.count = count;', ...
    '  job.values = mxGetPr(results[0]); job.ticks = mxGetPr(results[1]);', ...
    '  job.clocks = clocks; job.clock_count = clock_count;', ...
    '  job.status = OB_OK; job.failed = 0; job.steps = 0.0;', ...
    '  const char *message = "";', ...
    '  double call = 0.0;'}];
  if (events)
    lines = [lines {'  ob_accel_events.count = 0; ob_accel_events.failed = 0; ob_accel_events.search = 0.0;'}];
  endif
  if (external)
    lines = [lines { ...
      '  ob_accel_host host;', ...
      '  memset(&host, 0, sizeof(host));', ...
      '  host.helper = prhs[1];', ...
      '  if (!ob_accel_launch(&job, &host)) { job.status = -1; job.failed = 1; }', ...
      '  if (host.failed) { message = host.message; call = (double)host.failed; }'}];
  else
    lines = [lines {'  if (!ob_accel_launch(&job)) { job.status = -1; job.failed = 1; }'}];
  endif
  lines = [lines {'  mxFree(job.model);'}];
  if (events)
    lines = [lines { ...
      '  if (ob_accel_events.failed && job.status == OB_OK) { job.status = -1; job.failed = count; }', ...
      '  results[7] = mxCreateDoubleMatrix(ob_accel_events.count, 5, mxREAL);', ...
      '  for (size_t r = 0; r < ob_accel_events.count; ++r)', ...
      '    for (size_t c = 0; c < 5; ++c) mxGetPr(results[7])[r + c*ob_accel_events.count] = ob_accel_events.rows[5*r + c];', ...
      '  free(ob_accel_events.rows); ob_accel_events.rows = NULL; ob_accel_events.capacity = 0;'}];
  else
    lines = [lines {'  results[7] = mxCreateDoubleMatrix(0, 5, mxREAL);'}];
  endif
  lines = [lines { ...
    '  results[2] = mxCreateDoubleScalar((double)job.status);', ...
    '  results[3] = mxCreateDoubleScalar((double)job.failed);', ...
    '  results[4] = mxCreateDoubleScalar(job.steps);', ...
    '  results[5] = mxCreateString(message);', ...
    '  results[6] = mxCreateDoubleScalar(call);', ...
    '  /* Octave provides only max (nlhs, 1) output slots. */', ...
    '  for (int k = 0; k < 8; ++k) {', ...
    '    if (k < outputs) plhs[k] = results[k];', ...
    '    else mxDestroyArray(results[k]);', ...
    '  }', ...
    '}'}];
  text = [strjoin(lines, char (10)) char(10)];
endfunction

function lines = external_lines ()
  % Host side of ob_external_call (see the main help text).
  lines = { ...
    'typedef struct {', ...
    '  const mxArray *helper;', ...
    '  size_t index; const double *const *inputs; double *output; int status;', ...
    '  size_t failed; char message[1024]; int threaded;', ...
    '#if defined(_WIN32)', ...
    '  HANDLE request, reply;', ...
    '#elif defined(OB_ACCEL_PTHREAD)', ...
    '  pthread_mutex_t lock; pthread_cond_t changed; int state;', ...
    '#endif', ...
    '} ob_accel_host;', ...
    'static ob_accel_host *ob_accel_current;', ...
    '/* Main-thread runs: twice the rollback context, 32 value and state arrays', ...
    '   (evaluations, integrator stages, delay segments) and 64 KB of frames. */', ...
    'static const size_t ob_accel_main_need = 2*OB_ACCEL_CONTEXT_BYTES', ...
    '  + 32*((size_t)OB_VALUE_COUNT + (size_t)OB_STATE_STORAGE)*sizeof(double) + ((size_t)64 << 10);', ...
    '/* Main thread: evaluate one Function block. */', ...
    'static void ob_accel_serve(ob_accel_host *host) {', ...
    '  const size_t index = host->index, arity = ob_external_arity[index];', ...
    '  const size_t rows = ob_external_rows[index][0], cols = ob_external_cols[index][0];', ...
    '  mxArray *in[OB_EXTERNAL_WIDTH + 1], *out[2] = {NULL, NULL};', ...
    '  in[0] = (mxArray *)host->helper;', ...
    '  in[1] = mxCreateString(ob_external_name[index]);', ...
    '  for (size_t k = 0; k < arity; ++k) {', ...
    '    const size_t r = ob_external_rows[index][k+1], c = ob_external_cols[index][k+1];', ...
    '    in[2+k] = mxCreateDoubleMatrix(r, c, mxREAL);', ...
    '    memcpy(mxGetPr(in[2+k]), host->inputs[k], r*c*sizeof(double));', ...
    '  }', ...
    '  host->status = OB_OK;', ...
    '  /* Under the trap flag a failing call returns nonzero instead of', ...
    '     throwing; the helper then repeats it and returns its message. */', ...
    '  if (mexCallMATLAB(1, out, (int)arity, in + 2, ob_external_name[index]) != 0) {', ...
    '    if (out[0]) { mxDestroyArray(out[0]); out[0] = NULL; }', ...
    '    if (mexCallMATLAB(2, out, (int)(2 + arity), in, "feval") != 0) out[0] = out[1] = NULL;', ...
    '    if (!out[1]) {', ...
    '      host->status = OB_EXTERNAL_ERROR;', ...
    '      snprintf(host->message, sizeof(host->message), "the call failed");', ...
    '    } else if (mxGetNumberOfElements(out[1]) > 0) {', ...
    '      host->status = OB_EXTERNAL_ERROR;', ...
    '      if (mxGetString(out[1], host->message, sizeof(host->message)) != 0)', ...
    '        host->message[sizeof(host->message) - 1] = 0;', ...
    '    }', ...
    '  }', ...
    '  if (host->status == OB_OK) {', ...
    '    if (!out[0] || !mxIsDouble(out[0]) || mxIsComplex(out[0]) || mxIsSparse(out[0])', ...
    '        || mxGetNumberOfDimensions(out[0]) != 2 || mxGetM(out[0]) != rows || mxGetN(out[0]) != cols) {', ...
    '      host->status = OB_EXTERNAL_SHAPE;', ...
    '      char size[96] = "", part[32];', ...
    '      if (out[0]) {', ...
    '        const mwSize *dims = mxGetDimensions(out[0]);', ...
    '        for (mwSize d = 0; d < mxGetNumberOfDimensions(out[0]) && strlen(size) + 24 < sizeof(size); ++d) {', ...
    '          snprintf(part, sizeof(part), d ? "x%lu" : "%lu", (unsigned long)dims[d]);', ...
    '          strcat(size, part);', ...
    '        }', ...
    '      }', ...
    '      snprintf(host->message, sizeof(host->message), "returned %s%s %s value; the compiled model needs a real double %lux%lu matrix",', ...
    '               out[0] && mxIsComplex(out[0]) ? "a complex " : "a ", out[0] ? mxGetClassName(out[0]) : "no", size,', ...
    '               (unsigned long)rows, (unsigned long)cols);', ...
    '    } else {', ...
    '      /* ob_run keeps NaN/Inf results (a Scope accepts them), but the compiled', ...
    '         model stops on any nonfinite signal: unsupported, so that', ...
    '         accelerate=''auto'' falls back to the interpreter. */', ...
    '      const double *result = mxGetPr(out[0]);', ...
    '      for (size_t i = 0; i < rows*cols; ++i) if (!isfinite(result[i])) { host->status = OB_EXTERNAL_NONFINITE; break; }', ...
    '      if (host->status == OB_OK) memcpy(host->output, result, rows*cols*sizeof(double));', ...
    '      else snprintf(host->message, sizeof(host->message), "returned a nonfinite value; the compiled model needs finite signals");', ...
    '    }', ...
    '  }', ...
    '  if (host->status != OB_OK && !host->failed) host->failed = index + 1;', ...
    '  for (size_t k = 1; k < 2 + arity; ++k) mxDestroyArray(in[k]);', ...
    '  for (size_t k = 0; k < 2; ++k) if (out[k]) mxDestroyArray(out[k]);', ...
    '}', ...
    '/* Simulation side: evaluate directly on the main thread, or post the call', ...
    '   and wait for the main thread. */', ...
    'static int ob_external_call(size_t index, const double *const *inputs, double *output) {', ...
    '  ob_accel_host *host = ob_accel_current;', ...
    '  host->index = index; host->inputs = inputs; host->output = output;', ...
    '  if (!host->threaded) { ob_accel_serve(host); return host->status; }', ...
    '#if defined(_WIN32)', ...
    '  SetEvent(host->request);', ...
    '  WaitForSingleObject(host->reply, INFINITE);', ...
    '#elif defined(OB_ACCEL_PTHREAD)', ...
    '  pthread_mutex_lock(&host->lock);', ...
    '  host->state = 1; pthread_cond_broadcast(&host->changed);', ...
    '  while (host->state != 2) pthread_cond_wait(&host->changed, &host->lock);', ...
    '  host->state = 0;', ...
    '  pthread_mutex_unlock(&host->lock);', ...
    '#endif', ...
    '  return host->status;', ...
    '}', ...
    '#if defined(OB_ACCEL_PTHREAD) && !defined(_WIN32)', ...
    'typedef struct { ob_accel_job *job; ob_accel_host *host; } ob_accel_pair;', ...
    'static void *ob_accel_hosted(void *data) {', ...
    '  ob_accel_pair *pair = (ob_accel_pair *)data;', ...
    '  ob_accel_run(pair->job);', ...
    '  pthread_mutex_lock(&pair->host->lock);', ...
    '  pair->host->state = 3; pthread_cond_broadcast(&pair->host->changed);', ...
    '  pthread_mutex_unlock(&pair->host->lock);', ...
    '  return NULL;', ...
    '}', ...
    '#endif', ...
    'static int ob_accel_launch(ob_accel_job *job, ob_accel_host *host) {', ...
    '  ob_accel_current = host;', ...
    '  mexSetTrapFlag(1);', ...
    '  if (ob_accel_main_need <= ((size_t)256 << 10)) {', ...
    '    host->threaded = 0; ob_accel_run(job); return 1;', ...
    '  }', ...
    '#if defined(_WIN32)', ...
    '  int ok = 0;', ...
    '  host->request = CreateEvent(NULL, FALSE, FALSE, NULL);', ...
    '  host->reply = CreateEvent(NULL, FALSE, FALSE, NULL);', ...
    '  HANDLE thread = NULL;', ...
    '  if (host->request && host->reply)', ...
    '    thread = CreateThread(NULL, ob_accel_stack, ob_accel_thread, job, STACK_SIZE_PARAM_IS_A_RESERVATION, NULL);', ...
    '  if (thread) {', ...
    '    HANDLE waits[2] = {thread, host->request};', ...
    '    host->threaded = 1; ok = 1;', ...
    '    for (;;) {', ...
    '      const DWORD which = WaitForMultipleObjects(2, waits, FALSE, INFINITE);', ...
    '      if (which == WAIT_OBJECT_0) break;', ...
    '      if (which == WAIT_OBJECT_0 + 1) { ob_accel_serve(host); SetEvent(host->reply); continue; }', ...
    '      /* Cannot wait: fail the current or next call, so the worker stops. */', ...
    '      host->status = OB_EXTERNAL_ERROR; host->failed = host->index + 1;', ...
    '      snprintf(host->message, sizeof(host->message), "the accelerator could not wait for its simulation thread");', ...
    '      SetEvent(host->reply);', ...
    '      WaitForSingleObject(thread, INFINITE);', ...
    '      break;', ...
    '    }', ...
    '    CloseHandle(thread);', ...
    '  }', ...
    '  if (host->request) CloseHandle(host->request);', ...
    '  if (host->reply) CloseHandle(host->reply);', ...
    '  return ok;', ...
    '#elif defined(OB_ACCEL_PTHREAD)', ...
    '  pthread_attr_t attr; pthread_t thread; int ok = 0;', ...
    '  ob_accel_pair pair = {job, host};', ...
    '  if (pthread_mutex_init(&host->lock, NULL)) return 0;', ...
    '  if (pthread_cond_init(&host->changed, NULL)) { pthread_mutex_destroy(&host->lock); return 0; }', ...
    '  if (!pthread_attr_init(&attr)) {', ...
    '    if (!pthread_attr_setstacksize(&attr, ob_accel_stack) && !pthread_create(&thread, &attr, ob_accel_hosted, &pair)) {', ...
    '      host->threaded = 1; ok = 1;', ...
    '      pthread_mutex_lock(&host->lock);', ...
    '      for (;;) {', ...
    '        while (host->state != 1 && host->state != 3) pthread_cond_wait(&host->changed, &host->lock);', ...
    '        if (host->state == 3) break;', ...
    '        pthread_mutex_unlock(&host->lock);', ...
    '        ob_accel_serve(host);', ...
    '        pthread_mutex_lock(&host->lock);', ...
    '        host->state = 2; pthread_cond_broadcast(&host->changed);', ...
    '      }', ...
    '      pthread_mutex_unlock(&host->lock);', ...
    '      pthread_join(thread, NULL);', ...
    '    }', ...
    '    pthread_attr_destroy(&attr);', ...
    '  }', ...
    '  pthread_cond_destroy(&host->changed); pthread_mutex_destroy(&host->lock);', ...
    '  return ok;', ...
    '#else', ...
    '  host->threaded = 0; ob_accel_run(job); return 1;', ...
    '#endif', ...
    '}'};
endfunction
