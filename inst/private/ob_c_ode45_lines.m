function lines = ob_c_ode45_lines (o)
  % C99 adaptive Dormand-Prince 5(4) integrator for the flat ob_codegen exporter.
  %
  % The generated ob_ode45 ports Octave's own ode45 as ob_run calls it for
  % one integration segment (private/ob_runtime_integrate.m adaptive_segment:
  % ode45 (rhs, [begin finish], y0, odeset ('RelTol', reltol, 'AbsTol',
  % abstol, 'MaxStep', min (maxstep, finish - begin), 'Refine', 1))), one
  % operation per Octave operation in the same order:
  %
  %   starting_stepsize   initial step from the norms of y0, f(t0, y0) and a
  %                       difference quotient after one explicit Euler step
  %   integrate_adaptive  Kahan-summed step times (the compensation is also
  %                       updated by rejected steps, as in Octave), error
  %                       norm max |y5 - y4| / max (AbsTol, RelTol max (|y|,
  %                       |y_old|)), acceptance at err <= 1, the step factor
  %                       min (1.5, max (0.8, 0.38^(1/6) (1/(err + eps))^(1/6))),
  %                       MaxStep, the eps (t) step-size floor, the clipped
  %                       last step and at most 5000 consecutive rejections
  %   runge_kutta_45_dorpri  stages at t + h b_k with the Butcher table
  %                       scaled by h, FSAL reuse of the last stage, the
  %                       last stage at the Kahan time
  %   adaptive_rhs        stages at or past the segment end are evaluated at
  %                       the end with left limits
  %
  % The stage sums K * (h a_k)' are BLAS products in Octave.  They are
  % summed here in the order Octave's OpenBLAS uses for up to three
  % continuous states (one state: ddot, left to right from 0; two or three:
  % the generic dgemv kernel, which adds column pairs), which gives the
  % same rounding; with four or more states OpenBLAS uses FMA kernels whose
  % order depends on the CPU, and the plain left-to-right sum used instead
  % agrees to rounding.
  %
  % Limited Integrators saturate on each evaluation's output (no fixed-step
  % decision at the step start) and are clamped at accepted points, as
  % ob_run's adaptive path does.  With Transport Delays, every accepted
  % interior point is kept in the context's ode_t/ode_y scratch and,
  % after the whole segment, evaluated and recorded as a right limit in
  % order, exactly as adaptive_segment's caller records them; a segment with
  % more accepted points than OB_ODE_POINT_STORAGE returns OB_DELAY_OVERFLOW.
  %
  % o has fields count (continuous scalars), entries (struct array: state,
  % size, source, output, limited, id, level, reset), reltol, abstol,
  % maxstep, delays (record interior points), count_steps and points (the
  % size of the context's accepted-point scratch when delays is true).
  lines = {'/* SPDX-License-Identifier: GPL-3.0-or-later', ...
           ' * Copyright (C) 2006-2026 The Octave Project Developers', ...
           ' * Copyright (C) 2026 Shannon Ruan', ...
           ' * Adaptive solver adapted from GNU Octave 11.3.0.', ...
           ' * Redistribute/modify under GPL version 3 or later; no warranty.', ...
           ' * Include the GNU GPL text (COPYING) when distributing this code.', ...
           ' * https://www.gnu.org/licenses/gpl-3.0.html */'};
  n = o.count;
  a = [0 0 0 0 0; 1/5 0 0 0 0; 3/40 9/40 0 0 0; 44/45 -56/15 32/9 0 0; ...
       19372/6561 -25360/2187 64448/6561 -212/729 0; ...
       9017/3168 -355/33 46732/5247 49/176 -5103/18656];
  b = [0, 1/5, 3/10, 4/5, 8/9, 1, 1];
  c = [35/384, 0, 500/1113, 125/192, -2187/6784, 11/84];
  c_prime = [5179/57600, 0, 7571/16695, 393/640, -92097/339200, 187/2100, 1/40];
  % Scratch points exist only with Transport Delays (ob_integrate below).
  overflow = 'OB_STEP_FAILED';
  if (o.delays), overflow = 'OB_DELAY_OVERFLOW'; endif
  maxstep = 'HUGE_VAL';
  if (isfinite (o.maxstep)), maxstep = num (o.maxstep); endif
  add ('/* Adaptive Dormand-Prince 5(4): Octave''s ode45 for one segment (see ob_c_ode45_lines.m). */', ...
       sprintf ('enum { OB_ODE_COUNT = %d, OB_ODE_POINT_STORAGE = %d };', n, max (1, o.points)), ...
       sprintf ('static const double ob_ode_reltol = %s, ob_ode_abstol = %s, ob_ode_maxstep = %s;', ...
                num (o.reltol), num (o.abstol), maxstep), ...
       ['static const double ob_ode_a[6][5] = {' strjoin(arrayfun (@(r) ['{' num(a(r, :)) '}'], 1:6, 'uniformoutput', false), ',') '};'], ...
       ['static const double ob_ode_b[7] = {' num(b) '};'], ...
       ['static const double ob_ode_c[6] = {' num(c) '};'], ...
       ['static const double ob_ode_e[7] = {' num(c_prime) '};']);
  % Packed solver vector <-> context state (continuous blocks in id order,
  % elements in column order; the norms and products are per component).
  add ('static void ob_ode_scatter(double *state, const double *y) {');
  offset = 0;
  for e = o.entries
    add (sprintf ('  memcpy(state + %d, y + %d, %d * sizeof(double));', e.state, offset, e.size));
    offset += e.size;
  endfor
  add ('}', 'static void ob_ode_gather(const double *state, double *y) {');
  offset = 0;
  for e = o.entries
    add (sprintf ('  memcpy(y + %d, state + %d, %d * sizeof(double));', offset, e.state, e.size));
    offset += e.size;
  endfor
  add ('}');
  if (any ([o.entries.limited]))
    % clamp_states: min (max (x, lower), upper) with Octave's tie choices.
    add ('static void ob_ode_clamp(double *y) {', '  (void)y;');
    offset = 0;
    for e = o.entries
      if (e.limited)
        add (sprintf ('  for (size_t i = 0; i < %d; ++i) {', e.size), ...
             sprintf ('    const double clipped = y[%d + i] >= lo%d[i] ? y[%d + i] : lo%d[i];', offset, e.id, offset, e.id), ...
             sprintf ('    y[%d + i] = clipped <= hi%d[i] ? clipped : hi%d[i];', offset, e.id, e.id), '  }');
      endif
      offset += e.size;
    endfor
    add ('}');
  endif
  add ('/* adaptive_rhs: derivatives at (time, y), other states from base. */', ...
       'static int ob_ode_rhs(const ob_model *model, double time, double end, const double *base, const double *y, double *dy) {', ...
       '  double state[OB_STATE_STORAGE], v[OB_VALUE_COUNT];', ...
       '  memcpy(state, base, sizeof(state));', '  ob_ode_scatter(state, y);', ...
       '  const int left = time >= end;', '  if (left) time = end;', ...
       '  const int status = ob_eval(model, time, state, v, left, NULL, NULL);', ...
       '  if (status != OB_OK) return status;');
  offset = 0;
  for e = o.entries
    if (! e.limited)
      add (sprintf ('  memcpy(dy + %d, v + %d, %d * sizeof(double));', offset, e.source, e.size));
    else
      % A saturated output stops integrating outward; a nonzero level
      % reset holds the state (ob_runtime_integrate derivatives).
      add (sprintf ('  for (size_t i = 0; i < %d; ++i) {', e.size), ...
           sprintf ('    const double rate = v[%d + i], output = v[%d + i];', e.source, e.output), ...
           sprintf ('    dy[%d + i] = (output >= hi%d[i] && rate > 0.0) || (output <= lo%d[i] && rate < 0.0) ? 0.0 : rate;', offset, e.id, e.id), ...
           '  }');
      if (e.level)
        add (sprintf ('  if (v[%d] != 0.0)', e.reset), ...
             sprintf ('    for (size_t i = 0; i < %d; ++i) dy[%d + i] = 0.0;', e.size, offset));
      endif
    endif
    offset += e.size;
  endfor
  add ('  return OB_OK;', '}');
  % Stage sums in Octave's BLAS order (see above).
  add ('static double ob_ode_dot(const double (*k)[OB_ODE_COUNT], size_t i, const double *w, size_t terms) {', ...
       '  double sum = 0.0;', '  size_t j = 0;');
  if (n == 2 || n == 3)
    add ('  for (; j + 4 <= terms; j += 4) {', ...
         '    sum += k[j][i]*w[j] + k[j+1][i]*w[j+1];', ...
         '    sum += k[j+2][i]*w[j+2] + k[j+3][i]*w[j+3];', '  }');
  endif
  add ('  for (; j < terms; ++j) sum += k[j][i]*w[j];', '  return sum;', '}', ...
       '/* AbsRel_norm without NormControl; y == NULL means zeros. */', ...
       'static double ob_ode_norm(const double *x, const double *x_old, const double *y) {', ...
       '  double norm = 0.0;', ...
       '  for (size_t i = 0; i < OB_ODE_COUNT; ++i) {', ...
       '    const double scale = fmax(ob_ode_abstol, ob_ode_reltol * fmax(fabs(x[i]), fabs(x_old[i])));', ...
       '    const double value = fabs(x[i] - (y ? y[i] : 0.0)) / scale;', ...
       '    if (i == 0 || value > norm) norm = value;', '  }', '  return norm;', '}', ...
       '/* Octave eps (x): the spacing of doubles at |x|. */', ...
       'static double ob_ode_eps(double x) {', ...
       '  int exponent;', '  x = fabs(x);', ...
       '  if (x < DBL_MIN) return 4.9406564584124654e-324;', ...
       '  frexp(x, &exponent);', '  return ldexp(1.0, exponent - 53);', '}', ...
       '/* Integrate the continuous states over [start, end] in place.  Accepted', ...
       '   points (time, y) are stored when ode_t is not NULL; *points counts them', ...
       '   and *steps receives the number of accepted steps. */', ...
       'static int ob_ode45(const ob_model *model, double start, double end, double *state,', ...
       '                    double *ode_t, double *ode_y, size_t storage, size_t *points, double *steps) {', ...
       '  double x_old[OB_ODE_COUNT], x_new[OB_ODE_COUNT], x_est[OB_ODE_COUNT], stage[OB_ODE_COUNT];', ...
       '  double k[7][OB_ODE_COUNT], fsal[OB_ODE_COUNT], f0[OB_ODE_COUNT], f1[OB_ODE_COUNT], aa[5], cc[6], ee[7];', ...
       '  double base[OB_STATE_STORAGE];', '  int status;', ...
       '  (void)storage;', ...
       '  *points = 0; *steps = 0.0;', ...
       '  memcpy(base, state, sizeof(base));', '  ob_ode_gather(state, x_old);', ...
       '  const double maxstep = fmin(ob_ode_maxstep, end - start);', ...
       '  /* starting_stepsize (order 5) */', ...
       '  const double d0 = ob_ode_norm(x_old, x_old, NULL);', ...
       '  status = ob_ode_rhs(model, start, end, base, x_old, f0);', ...
       '  if (status != OB_OK) return status;', ...
       '  const double d1 = ob_ode_norm(f0, f0, NULL);', ...
       '  const double h0 = (d0 < 1e-5 || d1 < 1e-5) ? 1e-6 : 0.01 * (d0 / d1);', ...
       '  for (size_t i = 0; i < OB_ODE_COUNT; ++i) stage[i] = x_old[i] + h0 * f0[i];', ...
       '  status = ob_ode_rhs(model, start + h0, end, base, stage, f1);', ...
       '  if (status != OB_OK) return status;', ...
       '  for (size_t i = 0; i < OB_ODE_COUNT; ++i) f1[i] = f1[i] - f0[i];', ...
       '  const double d2 = (1.0 / h0) * ob_ode_norm(f1, f1, NULL);', ...
       '  const double d12 = fmax(d1, d2);', ...
       '  const double h1 = d12 <= 1e-15 ? fmax(1e-6, h0 * 1e-3) : pow(1e-2 / d12, 1.0 / 6.0);', ...
       '  /* integrate_adaptive */', ...
       '  double dt = fmin(fmin(100.0 * h0, h1), maxstep);', ...
       '  double t_old = start, last = start, comp = 0.0;', ...
       '  const double fac = pow(0.38, 1.0 / 6.0);', ...
       '  int have_k = 0;', '  size_t reject = 0;', ...
       '  while (t_old < end) {', ...
       '    const double kahan = dt - comp;', ...
       '    const double t_new = t_old + kahan;', ...
       '    comp = (t_new - t_old) - kahan;', ...
       '    /* FSAL: the last stage of the last accepted step (k_vals in Octave). */', ...
       '    if (have_k) memcpy(k[0], fsal, sizeof(fsal));', ...
       '    else {', '      status = ob_ode_rhs(model, t_old, end, base, x_old, k[0]);', ...
       '      if (status != OB_OK) return status;', '    }', ...
       '    for (size_t s = 1; s < 6; ++s) {', ...
       '      for (size_t j = 0; j < s; ++j) aa[j] = dt * ob_ode_a[s][j];', ...
       '      if (s == 1) for (size_t i = 0; i < OB_ODE_COUNT; ++i) stage[i] = x_old[i] + k[0][i]*aa[0];', ...
       '      else for (size_t i = 0; i < OB_ODE_COUNT; ++i) stage[i] = x_old[i] + ob_ode_dot((const double (*)[OB_ODE_COUNT])k, i, aa, s);', ...
       '      status = ob_ode_rhs(model, t_old + dt * ob_ode_b[s], end, base, stage, k[s]);', ...
       '      if (status != OB_OK) return status;', '    }', ...
       '    for (size_t j = 0; j < 6; ++j) cc[j] = dt * ob_ode_c[j];', ...
       '    for (size_t i = 0; i < OB_ODE_COUNT; ++i) x_new[i] = x_old[i] + ob_ode_dot((const double (*)[OB_ODE_COUNT])k, i, cc, 6);', ...
       '    status = ob_ode_rhs(model, t_new, end, base, x_new, k[6]);', ...
       '    if (status != OB_OK) return status;', ...
       '    for (size_t j = 0; j < 7; ++j) ee[j] = dt * ob_ode_e[j];', ...
       '    for (size_t i = 0; i < OB_ODE_COUNT; ++i) x_est[i] = x_old[i] + ob_ode_dot((const double (*)[OB_ODE_COUNT])k, i, ee, 7);', ...
       '    double err = ob_ode_norm(x_new, x_old, x_est);', ...
       '    if (err <= 1.0) {', ...
       '      reject = 0;', '      *steps += 1.0;', '      last = t_new;', ...
       '      if (ode_t) {', ...
       sprintf ('        if (*points >= storage) return %s;', overflow), ...
       '        ode_t[*points] = t_new;', ...
       '        memcpy(ode_y + *points * OB_ODE_COUNT, x_new, sizeof(x_new));', ...
       '      }', '      *points += 1;', ...
       '      t_old = t_new;', '      memcpy(x_old, x_new, sizeof(x_old));', ...
       '      memcpy(fsal, k[6], sizeof(fsal));', '      have_k = 1;', ...
       '    } else if (++reject >= 5000) {', '      return OB_STEP_FAILED;', '    }', ...
       '    err += DBL_EPSILON;', ...
       '    dt *= fmin(1.5, fmax(0.8, fac * pow(1.0 / err, 1.0 / 6.0)));', ...
       '    dt = fmin(fabs(dt), maxstep);', ...
       '    if (!(fabs(dt) > ob_ode_eps(last))) break;', ...
       '    dt = fmin(fabs(dt), fabs(end - t_old));', '  }', ...
       '  /* adaptive_segment: the last accepted time must be the segment end. */', ...
       '  const double tolerance = 8.0 * DBL_EPSILON * fmax(DBL_MIN, fmax(fabs(start), fabs(end)));', ...
       '  if (*steps < 1.0 || !isfinite(last) || last <= start || fabs(last - end) > tolerance) return OB_STEP_FAILED;', ...
       '  for (size_t i = 0; i < OB_ODE_COUNT; ++i) if (!isfinite(x_old[i])) return OB_STEP_FAILED;');
  if (any ([o.entries.limited])), add ('  ob_ode_clamp(x_old);'); endif
  add ('  ob_ode_scatter(state, x_old);', '  return OB_OK;', '}');
  if (o.delays)
    % Same signature as the RK4 integrator called by ob_delay_segment.
    add ('/* One delay segment: integrate, then record every accepted interior point', ...
         '   (right limits, in order) after the whole segment, as ob_run does. */', ...
         'static int ob_integrate(ob_model *model, double start, double end, double *state, const double *initial) {', ...
         '  size_t points = 0;', '  double steps = 0.0;', '  (void)initial;', ...
         '  int status = ob_ode45(model, start, end, state, model->ode_t, model->ode_y, OB_ODE_POINT_STORAGE, &points, &steps);');
    if (o.count_steps), add ('  if (status == OB_OK) model->integration_steps += steps;'); endif
    add ('  for (size_t p = 0; status == OB_OK && p + 1 < points; ++p) {', ...
         '    double sample[OB_STATE_STORAGE], values[OB_VALUE_COUNT], y[OB_ODE_COUNT];', ...
         '    memcpy(sample, model->state, sizeof(sample));', ...
         '    memcpy(y, model->ode_y + p * OB_ODE_COUNT, sizeof(y));');
    if (any ([o.entries.limited])), add ('    ob_ode_clamp(y);'); endif
    add ('    ob_ode_scatter(sample, y);', ...
         '    status = ob_eval(model, model->ode_t[p], sample, values, 0, NULL, NULL);', ...
         '    if (status == OB_OK) status = ob_delay_record_all(model, model->ode_t[p], values, 0);', ...
         '  }', ...
         '  /* Scratch is not context state: keep it zero between calls. */', ...
         '  if (points > OB_ODE_POINT_STORAGE) points = OB_ODE_POINT_STORAGE;', ...
         '  memset(model->ode_t, 0, points * sizeof(double));', ...
         '  memset(model->ode_y, 0, points * OB_ODE_COUNT * sizeof(double));', ...
         '  return status;', '}');
  endif

  function add (varargin)
    lines = [lines varargin];
  endfunction
endfunction

function text = num (values)
  text = ob_c_number_list (values);
endfunction
