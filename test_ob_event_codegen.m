function test_ob_event_codegen (directory, verify = false, pattern = '.*')
  % Prepare event exports and compare every numeric channel after C execution.
  % Test-EventCodegen.ps1 performs strict compilation between these two phases.
  if (verify)
    verify_exports (directory);
    return;
  endif
  if (! exist(directory,'dir')), mkdir(directory); endif
  [fixtures, specifications] = test_ob_event_codegen_cases ();
  manifest = struct ('name',{},'source',{},'standalone',{},'expected',{});
  exported = {};
  for fixture = fixtures
    if (isempty(regexp(fixture.name,pattern,'once'))), continue; endif
    source = [fixture.name '.c']; expected_file = [fixture.name '.expected.csv'];
    info = ob_codegen (fixture.model,fullfile(directory,source),fixture.config,fixture.options);
    result = ob_run (fixture.model,ob_time_grid(fixture.config(1),fixture.config(2),fixture.config(3)),fixture.options);
    assert (numel(info.shapes)==numel(result.compiled_model.blocks), ...
            ['event export metadata length: ' fixture.name]);
    expected = result.t;
    for block = 1:numel(result.compiled_model.blocks)
      count = prod(info.shapes{block});
      if (count==0), continue; endif % Typed conditional cores have no numeric channels.
      traces = zeros(numel(result.t),count);
      for sample = 1:numel(result.t)
        value = result.flat_values{sample,block};
        assert (isnumeric(value) && isreal(value) && isequal(size(value),info.shapes{block}), ...
                ['event export reference shape: ' fixture.name]);
        traces(sample,:) = value(:)';
      endfor
      assert (all(isfinite(traces(:))),['nonfinite event reference: ' fixture.name]);
      expected = [expected traces];
    endfor
    dlmwrite (fullfile(directory,expected_file),expected,'precision','%.17g');
    manifest(end+1) = struct('name',fixture.name,'source',source, ...
                            'standalone',true,'expected',expected_file);
    exported{end+1} = fixture.name;
  endfor
  assert (! isempty(exported),'test_ob_event_codegen: pattern selected no event fixtures');
  if (any(strcmp(exported,'event_host_inputs')))
    add_api ('api_event_inputs', input_harness());
  endif
  if (any(strcmp(exported,'event_host_chatter')))
    add_api ('api_event_chatter', chatter_harness());
  endif
  write_text (fullfile(directory,'event-manifest.json'),jsonencode(manifest));
  write_text (fullfile(directory,'event-api-specifications.json'),jsonencode(specifications));
  fprintf ('Prepared %d event C compilation/API cases (%d numeric models)\n', ...
           numel(manifest),numel(exported));

  function add_api (name, lines)
    source = [name '.c'];
    write_text (fullfile(directory,source),[strjoin(lines,char(10)) char(10)]);
    manifest(end+1) = struct('name',name,'source',source,'standalone',false,'expected','');
  endfunction
endfunction

function verify_exports (directory)
  manifest = jsondecode(fileread(fullfile(directory,'event-manifest.json')));
  worst = 0; compared = 0; channels = 0;
  for index_case = 1:numel(manifest)
    item = manifest(index_case);
    if (! item.standalone), continue; endif
    expected = dlmread(fullfile(directory,item.expected),',');
    actual = dlmread(fullfile(directory,[item.name '.csv']),',',1,0);
    assert (isequal(size(actual),size(expected)),['event CSV shape mismatch: ' item.name]);
    assert (all(isfinite(actual(:))),['nonfinite event C output: ' item.name]);
    scaled = abs(actual-expected)./max(1,abs(expected));
    [error,index] = max(scaled(:));
    [sample,column] = ind2sub(size(expected),index);
    assert (error<2e-8,sprintf(['event C/Octave mismatch for %s sample %d column %d: ' ...
              'actual %.17g expected %.17g scaled error %.17g'], ...
              item.name,sample,column,actual(index),expected(index),error));
    worst = max(worst,error); compared += 1; channels += columns(actual)-1;
  endfor
  fprintf ('Compared %d event C models (%d numeric channels); worst scaled error %.3g\n', ...
           compared,channels,worst);
endfunction

