function write_text (file, text)
  fid = fopen(file,'wb');
  if (fid<0), error('test_ob_event_codegen: cannot write %s',file); endif
  unwind_protect
    assert(fwrite(fid,text,'char')==numel(text));
  unwind_protect_cleanup
    fclose(fid);
  end_unwind_protect
endfunction
